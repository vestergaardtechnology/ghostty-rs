/// The raw OpenGL/EGL C API (Zig: `@import("opengl_c")`, a translate-c of
/// the vendored `glad/gl.h` (GL 4.3 core, MX loader) and `glad/glad_egl.h`
/// (EGL 1.5 + EGL_MESA_image_dma_buf_export, EGL_MESA_platform_surfaceless)).
///
/// `c_bindings.rs` is generated by rust-bindgen 0.73 from those headers;
/// `vendor/glad/src/{gl,glad_egl}.c` are compiled by `build.rs`.
