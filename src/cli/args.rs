impl ParseCli for bool {
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
        parse_bool(input.unwrap_or("t"))
    }
}

#[allow(unused_macros)]
macro_rules! impl_parse_cli_int {
    ($($t:ty),*) => {$(
        impl ParseCli for $t {
            fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
                parse_int::<$t>(input.ok_or(Error::ValueRequired)?, 0)
                    .map_err(|_| Error::InvalidValue)
            }
        }
    )*};
}
impl_parse_cli_int!(u8, u16, u32, u64, usize, i8, i16, i32, i64, isize);

impl ParseCli for f64 {
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
        parse_float(input.ok_or(Error::ValueRequired)?).map_err(|_| Error::InvalidValue)
    }
}

impl ParseCli for f32 {
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
        let input = input.ok_or(Error::ValueRequired)?;
        // Parse directly as f32 when possible for correct rounding.
        if let Ok(v) = input.parse::<f32>() {
            if parse_float(input).is_ok() {
                return Ok(v);
            }
        }
        parse_float(input)
            .map(|v| v as f32)
            .map_err(|_| Error::InvalidValue)
    }
}

impl ParseCli for String {
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
        Ok(input.ok_or(Error::ValueRequired)?.to_owned())
    }
}

impl ParseCli for StringZ {
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
        Ok(StringZ::from(input.ok_or(Error::ValueRequired)?))
    }
}

/// For optional fields, we just treat it as the child type. This lets
/// optional fields default to null but get set by the CLI.
impl<T: ParseCli> ParseCli for Option<T> {
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
        Ok(Some(T::parse_cli_new(input)?))
    }

    fn parse_cli(&mut self, input: Option<&str>) -> Result<(), Error> {
        match self {
            // If the field is optional and set, then we use
            // the pointer value directly into it.
            Some(v) => v.parse_cli(input),
            // If its not set we need to create a new instance.
            None => {
                *self = Some(T::parse_cli_new(input)?);
                Ok(())
            }
        }
    }
}

