/// The base errors for arg parsing. Additional errors can be returned due
/// to type-specific parsing but these are always possible.
///
/// Zig's inferred error sets are merged into this one enum: the three base
/// errors, `OutOfMemory`, and any other named error as [`Error::Other`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Error {
    ValueRequired,
    InvalidField,
    InvalidValue,
    OutOfMemory,
    /// Any other (type-specific) Zig error, by its Zig name.
    Other(&'static str),
}

impl Error {
    /// The Zig error name (without the `error.` prefix).
    pub fn name(self) -> &'static str {
        match self {
            Error::ValueRequired => "ValueRequired",
            Error::InvalidField => "InvalidField",
            Error::InvalidValue => "InvalidValue",
            Error::OutOfMemory => "OutOfMemory",
            Error::Other(name) => name,
        }
    }
}

impl fmt::Display for Error {
    /// Formats like Zig's `{}` on an error value: `error.Name`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "error.{}", self.name())
    }
}

impl std::error::Error for Error {}

impl From<comma_splitter::Error> for Error {
    fn from(err: comma_splitter::Error) -> Self {
        Error::Other(err.name())
    }
}

impl From<string::Error> for Error {
    fn from(err: string::Error) -> Self {
        match err {
            string::Error::OutOfMemory => Error::OutOfMemory,
            other => Error::Other(other.name()),
        }
    }
}

