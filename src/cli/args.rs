/// An owned UTF-8 string that is always followed by a NUL byte: the Rust
/// counterpart of Zig's `[:0]const u8`. It derefs to `str` (without the
/// NUL) and can hand out a C string pointer that stays valid as long as the
/// value lives, which the C API (`config/c_get.zig`) relies on.
#[derive(Clone)]
pub struct StringZ {
    /// Invariant: always ends with a single trailing `'\0'`.
    buf: String,
}

impl StringZ {
    pub fn new() -> StringZ {
        StringZ {
            buf: String::from("\0"),
        }
    }

    /// The string without the trailing NUL.
    pub fn as_str(&self) -> &str {
        &self.buf[..self.buf.len() - 1]
    }

    /// The bytes including the trailing NUL.
    pub fn as_bytes_with_nul(&self) -> &[u8] {
        self.buf.as_bytes()
    }

    /// The value as a C string. If the value contains an interior NUL the C
    /// string ends there (like Zig's `[*:0]const u8`).
    pub fn as_c_str(&self) -> &CStr {
        CStr::from_bytes_until_nul(self.buf.as_bytes()).expect("StringZ is NUL-terminated")
    }

    /// Pointer to the NUL-terminated bytes.
    pub fn as_ptr(&self) -> *const c_char {
        self.buf.as_ptr() as *const c_char
    }

    /// Length without the trailing NUL.
    pub fn len(&self) -> usize {
        self.buf.len() - 1
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    pub fn into_string(mut self) -> String {
        self.buf.pop();
        self.buf
    }
}

impl Default for StringZ {
    fn default() -> Self {
        StringZ::new()
    }
}

impl std::ops::Deref for StringZ {
    type Target = str;
    fn deref(&self) -> &str {
        self.as_str()
    }
}

impl AsRef<str> for StringZ {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl std::borrow::Borrow<str> for StringZ {
    fn borrow(&self) -> &str {
        self.as_str()
    }
}

impl From<&str> for StringZ {
    fn from(s: &str) -> Self {
        let mut buf = String::with_capacity(s.len() + 1);
        buf.push_str(s);
        buf.push('\0');
        StringZ { buf }
    }
}

impl From<String> for StringZ {
    fn from(mut buf: String) -> Self {
        buf.push('\0');
        StringZ { buf }
    }
}

impl From<&String> for StringZ {
    fn from(s: &String) -> Self {
        StringZ::from(s.as_str())
    }
}

impl PartialEq for StringZ {
    fn eq(&self, other: &Self) -> bool {
        self.buf == other.buf
    }
}

impl Eq for StringZ {}

impl PartialEq<str> for StringZ {
    fn eq(&self, other: &str) -> bool {
        self.as_str() == other
    }
}

impl PartialEq<&str> for StringZ {
    fn eq(&self, other: &&str) -> bool {
        self.as_str() == *other
    }
}

impl PartialOrd for StringZ {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for StringZ {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        self.as_str().cmp(other.as_str())
    }
}

impl std::hash::Hash for StringZ {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.as_str().hash(state)
    }
}

impl fmt::Debug for StringZ {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Debug::fmt(self.as_str(), f)
    }
}

impl fmt::Display for StringZ {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Display::fmt(self.as_str(), f)
    }
}

