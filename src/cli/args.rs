//! Port of `src/cli/args.zig`.
//!
//! STATUS: ported
//!
//! # Design: comptime reflection → traits + `macro_rules!`
//!
//! Zig's `args.parse(T, alloc, &dst, iter)` walks the fields of the struct
//! type `T` at comptime and parses each `--key=value` argument into the
//! field named `key`, using either a built-in rule for the field's type or
//! the type's own `parseCLI` decl. `config/formatter.zig` does the reverse
//! with each type's `formatEntry`. Rust has no reflection, so the port
//! splits this into:
//!
//! * **Per-type traits**, implemented once per field type:
//!   * [`ParseCli`]: how one value is parsed. This replaces both Zig's
//!     built-in rules and `parseCLI`/`init` decls. It is implemented here
//!     for `bool`, all integers (Zig `std.fmt.parseInt(T, v, 0)`), `f32`/`f64`,
//!     `String` (Zig `[]const u8`), [`StringZ`] (Zig `[:0]const u8`) and
//!     `Option<T>` (Zig `?T`), and generated by the macros below for enums,
//!     packed structs, plain ("auto") structs and tagged unions.
//!   * [`FormatEntry`](crate::config::formatter::FormatEntry): Zig
//!     `formatEntry` (see `config/formatter.rs`).
//!   * `Clone` replaces Zig's `clone(alloc)` decls and `Config.cloneValue`;
//!     `PartialEq` replaces `equal` decls and `deepEqual`.
//! * **Per-struct macros** that generate the field dispatch Zig gets from
//!   `inline for (@typeInfo(T).@"struct".field_names ...)`:
//!   * [`cli_struct!`] defines a struct and implements [`Fields`]:
//!     `parse_into_field(key, value)` (Zig `parseIntoField`),
//!     `parse_auto_struct` (Zig `parseAutoStruct`, the `key:value,...`
//!     syntax) and the [`Fields::FIELDS`] table (name, doc comment lines
//!     — Zig's `help_strings` — and enum values for diagnostics). Optional
//!     extras generate [`FormatFields`] (per-field formatting, used by
//!     `formatter_file`), [`ChangedFields`] (per-field `!=`, used by
//!     `Config.changed`) and a [`ParseCli`] impl using the auto-struct rule.
//!   * [`cli_enum!`] / [`impl_cli_enum!`]: Zig enums whose tag names are
//!     user-visible (`std.meta.stringToEnum`, `@tagName`). Every variant
//!     names its exact Zig tag, so `foo-bar` and `foo_bar` both work.
//!   * [`cli_flags!`]: Zig `packed struct` of bools (`bold,no-italic`).
//!   * [`cli_union!`]: Zig `union(enum)` parsed with the built-in
//!     `tag:value` rule ([`parse_tagged_union`]).
//! * **Per-struct hooks**: [`ParseHooks`] replaces the optional decls and
//!   fields `parse` looks for: `_diagnostics` ([`ParseHooks::diagnostics_mut`]),
//!   `compatibility` ([`ParseHooks::compatibility`]), `parseManuallyHook`
//!   and `help`. `cli_struct!` generates an empty impl unless the
//!   `custom_hooks` extra is given.
//!
//! The arena (`_arena`) is dropped: every value owns its memory.
//! Arguments are UTF-8 `&str`/`String` (non-UTF-8 process args and config
//! files are converted lossily by the iterators below).
//!
//! ## Mapping Zig field types
//!
//! | Zig field type | Rust field type |
//! | --- | --- |
//! | `bool`, `u8`…`u64`, `usize`, `i8`…`i64`, `f32`, `f64` | same (`u21` → `u32`) |
//! | `[]const u8` | `String` |
//! | `[:0]const u8` | [`StringZ`] (keeps a trailing NUL for C APIs) |
//! | `?T` | `Option<T>` |
//! | `enum { foo, @"bar-baz" }` | [`cli_enum!`] |
//! | `packed struct { a: bool = true }` | [`cli_flags!`] |
//! | `struct` without `parseCLI` | [`cli_struct!`] with `with { parse_cli }` |
//! | `union(enum)` without `parseCLI` | [`cli_union!`] |
//! | any type with `parseCLI` | hand-written `impl ParseCli` (below) |
//!
//! ## Mapping `parseCLI`, `init`, `clone`, `equal`, `formatEntry`
//!
//! * `pub fn parseCLI(input: ?[]const u8) !T` (1 arg) → implement
//!   [`ParseCli::parse_cli_new`] only (the default `parse_cli` replaces
//!   `*self`).
//! * `pub fn parseCLI(self: *T, [alloc,] input: ?[]const u8) !void` (2/3 args,
//!   mutating, e.g. repeatable values) → implement [`ParseCli::parse_cli`],
//!   and `parse_cli_new` as `args::parse_cli_new_from_default(input)` (Zig
//!   parses into an `undefined` temporary when an optional field is null; we
//!   start from `Default`) or by building the value directly.
//! * `pub fn init(self: *T, alloc) !void` (called when the value is the
//!   empty string, e.g. `keybind =`) → implement [`ParseCli::init_cli`].
//! * enums with their own `parseCLI` → `cli_enum! { @custom_parse ... }`
//!   and a hand-written `ParseCli` that sets
//!   `const ENUM_VALUES = Some(<Self as CliEnum>::FIELD_NAMES)`.
//! * `clone(alloc)` → `#[derive(Clone)]`/`impl Clone`; `equal` →
//!   `PartialEq`; `formatEntry` → `impl FormatEntry`.
//! * Errors: type-specific Zig errors (e.g. `error.InvalidFormat`) become
//!   [`Error::Other("InvalidFormat")`](Error::Other).
//!
//! ## Worked example (mirrors `Config.zig`)
//!
//! This compiles as the `worked_example` unit test at the bottom of this
//! file.
//!
//! ```ignore
//! use crate::cli::args::{
//!     self, cli_enum, cli_flags, cli_struct, compatibility_renamed, ArgIterator,
//!     CompatibilityHandler, Error, ParseCli, ParseHooks, StringZ,
//! };
//! use crate::cli::diagnostics::DiagnosticList;
//! use crate::config::formatter::{self, EntryFormatter, FormatEntry};
//!
//! cli_enum! {
//!     /// Valid values for confirm-close-surface
//!     /// c_int because it needs to be extern compatible
//!     #[repr(C)]
//!     pub enum ConfirmCloseSurface {
//!         False => "false",
//!         True => "true",
//!         Always => "always",
//!     }
//! }
//!
//! cli_flags! {
//!     /// Shell integration features
//!     pub struct ShellIntegrationFeatures {
//!         pub cursor: bool = true,
//!         pub sudo: bool = false,
//!         pub ssh_env as "ssh-env": bool = false,
//!     }
//! }
//!
//! /// Zig: `pub fn parseCLI(input: ?[]const u8) !Color` (1 arg).
//! #[derive(Debug, Clone, Copy, PartialEq, Eq)]
//! pub struct Color { pub r: u8, pub g: u8, pub b: u8 }
//!
//! impl ParseCli for Color {
//!     fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
//!         let input = input.ok_or(Error::ValueRequired)?;
//!         let hex = input.strip_prefix('#').unwrap_or(input);
//!         if hex.len() != 6 { return Err(Error::Other("InvalidFormat")); }
//!         let c = |i: usize| u8::from_str_radix(&hex[i..i + 2], 16)
//!             .map_err(|_| Error::InvalidValue);
//!         Ok(Color { r: c(0)?, g: c(2)?, b: c(4)? })
//!     }
//! }
//!
//! impl FormatEntry for Color {
//!     fn format_entry(&self, f: &mut EntryFormatter<'_>) -> Result<(), formatter::Error> {
//!         f.format_entry(&format!("#{:02x}{:02x}{:02x}", self.r, self.g, self.b))
//!     }
//! }
//!
//! /// Zig: `pub fn parseCLI(self: *Self, alloc: Allocator, input: ?[]const u8) !void`
//! /// (mutating) plus `clone`, `equal`, `formatEntry`.
//! #[derive(Debug, Clone, Default, PartialEq)]
//! pub struct RepeatableString { pub list: Vec<StringZ> }
//!
//! impl ParseCli for RepeatableString {
//!     fn parse_cli(&mut self, input: Option<&str>) -> Result<(), Error> {
//!         let value = input.ok_or(Error::ValueRequired)?;
//!         // Empty value resets the list
//!         if value.is_empty() { self.list.clear(); return Ok(()); }
//!         self.list.push(value.into());
//!         Ok(())
//!     }
//!     fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
//!         args::parse_cli_new_from_default(input)
//!     }
//! }
//!
//! impl FormatEntry for RepeatableString {
//!     fn format_entry(&self, f: &mut EntryFormatter<'_>) -> Result<(), formatter::Error> {
//!         if self.list.is_empty() { return f.format_entry(&()); }
//!         for v in &self.list { f.format_entry(v)?; }
//!         Ok(())
//!     }
//! }
//!
//! cli_struct! {
//!     /// Config is the main config struct.
//!     #[derive(Debug, Clone)]
//!     pub struct Config {
//!         /// The font families to use.
//!         ///
//!         /// This configuration can be repeated multiple times.
//!         pub font_family as "font-family": RepeatableString = RepeatableString::default(),
//!         /// Font size in points.
//!         pub font_size as "font-size": f32 = 13.0,
//!         pub language: Option<StringZ> = None,
//!         pub background: Color = Color { r: 0x28, g: 0x2c, b: 0x34 },
//!         pub confirm_close_surface as "confirm-close-surface": ConfirmCloseSurface =
//!             ConfirmCloseSurface::True,
//!         pub shell_integration_features as "shell-integration-features":
//!             ShellIntegrationFeatures = ShellIntegrationFeatures::default(),
//!         pub background_blur as "background-blur": u8 = 0,
//!         pub bold_is_bright as "bold-is-bright": bool = false,
//!     }
//!     // Zig fields starting with `_` (never parsed, formatted or compared).
//!     private {
//!         pub _diagnostics: DiagnosticList = DiagnosticList::default(),
//!         pub _xdg_terminal_exec: bool = false,
//!     }
//!     with { format, changed, custom_hooks }
//! }
//!
//! impl ParseHooks for Config {
//!     fn diagnostics_mut(&mut self) -> Option<&mut DiagnosticList> {
//!         Some(&mut self._diagnostics)
//!     }
//!
//!     // Zig: `pub const compatibility = std.StaticStringMap(...)`.
//!     fn compatibility(key: &str) -> Option<CompatibilityHandler<Self>> {
//!         match key {
//!             "background-blur-radius" => Some(compatibility_renamed!(Config, "background-blur")),
//!             "old-bold" => Some(compat_old_bold),
//!             _ => None,
//!         }
//!     }
//!
//!     fn parse_manually_hook<I: ArgIterator + ?Sized>(
//!         &mut self, arg: &str, iter: &mut I,
//!     ) -> Result<bool, Error> {
//!         if arg == "-e" { while iter.next().is_some() {} return Ok(false); }
//!         Ok(true)
//!     }
//! }
//!
//! fn compat_old_bold(cfg: &mut Config, _key: &str, value: Option<&str>) -> bool {
//!     match args::parse_bool(value.unwrap_or("t")) {
//!         Ok(b) => { cfg.bold_is_bright = b; true }
//!         Err(_) => false,
//!     }
//! }
//!
//! // Loading: `cli.args.parse(Config, alloc, &cfg, &iter)`.
//! let mut cfg = Config::default();
//! let mut iter = args::LineIterator::init("font-size = 14\nbackground-blur-radius=20\n".as_bytes());
//! args::parse(&mut cfg, &mut iter).unwrap();
//! // Formatting all fields (Zig `formatter_file.zig`):
//! let mut out = String::new();
//! for i in 0..Config::FIELDS.len() { cfg.format_field(i, &mut out).unwrap(); }
//! // Help strings (Zig `help_strings.Config.@"font-family"`):
//! assert_eq!(Config::FIELDS[0].help(), "The font families to use.\n\nThis configuration can be repeated multiple times.");
//! ```
//!
//! Notes for macro users:
//! * `cli_enum!`/`cli_flags!` add `#[derive(Debug, Clone, Copy, PartialEq,
//!   Eq, Hash)]` themselves; `cli_struct!`/`cli_union!` do not derive
//!   anything (add derives yourself; `Clone` is required on all field types
//!   of a `cli_struct!` because of [`Fields::parse_auto_struct`]).
//! * `cli_struct!` implements `Default` (from the field defaults) only when
//!   every field has a default (`= expr`). Fields without a default behave
//!   like Zig fields without a default value (no reset on empty value,
//!   required in auto-struct syntax).
//! * `#[cfg]` attributes on fields are not supported.
//! * The config key is `stringify!(field)` unless `as "zig-name"` is given;
//!   raw identifiers (`r#type`) always need `as "type"`.
//! * Field indices into [`Fields::FIELDS`] are the declaration order of the
//!   non-private fields, i.e. the order of Zig's `config/key.zig` `Key`
//!   enum, so a Rust `Key` enum with the same order can be used as an index
//!   for [`FormatFields::format_field`] and [`ChangedFields::field_changed`].
//! * Zig's `_arena`, `_replay_steps`, `_conditional_state`, etc. go in the
//!   `private { ... }` block; they are not parsed, formatted or compared,
//!   and in [`Fields::parse_auto_struct`] they take their default.

