/// How a single value is parsed from a CLI/config value. This replaces
/// both Zig's built-in per-type rules in `parseIntoField` and the
/// `parseCLI`/`init` decls. See the module docs.
pub trait ParseCli: Sized {
    /// The valid values listed in "invalid value" diagnostics. Zig lists
    /// the tag names when the field type is an enum (`formatValues`).
    const ENUM_VALUES: Option<&'static [&'static str]> = None;

    /// Parse a new value (Zig: 1-arg `parseCLI(input) !T`, or the built-in
    /// rule). For mutating parsers this is called when the destination is a
    /// null optional (Zig parses into an `undefined` temporary).
    fn parse_cli_new(input: Option<&str>) -> Result<Self, Error>;

    /// Parse into an existing value (Zig: 2/3-arg
    /// `parseCLI(self, [alloc,] input) !void`). The default replaces
    /// `*self` with [`ParseCli::parse_cli_new`].
    fn parse_cli(&mut self, input: Option<&str>) -> Result<(), Error> {
        *self = Self::parse_cli_new(input)?;
        Ok(())
    }

    /// Zig: `pub fn init(self: *T, alloc) !void`. If the type has one, it
    /// is used instead of the field default when the value is the empty
    /// string. `None` means the type has no `init`.
    fn init_cli() -> Option<Result<Self, Error>> {
        None
    }
}

/// Helper for mutating [`ParseCli`] implementations: build a new value by
/// parsing into `T::default()` (stand-in for Zig's `undefined` temporary).
pub fn parse_cli_new_from_default<T: ParseCli + Default>(input: Option<&str>) -> Result<T, Error> {
    let mut v = T::default();
    v.parse_cli(input)?;
    Ok(v)
}

/// An enum with user-visible Zig tag names. Generated by [`cli_enum!`] and
/// [`impl_cli_enum!`].
pub trait CliEnum: Sized + Copy + 'static {
    /// The Zig tag names in declaration order
    /// (`@typeInfo(E).@"enum".field_names`).
    const FIELD_NAMES: &'static [&'static str];

    /// Zig `@tagName(self)`.
    fn tag_name(self) -> &'static str;

    /// Zig `std.meta.stringToEnum(E, tag)`.
    fn from_tag(tag: &str) -> Option<Self>;

    /// Zig `@tagName(self)` as a NUL-terminated C string (Zig tag names
    /// are `[:0]const u8`). Generated by [`cli_enum!`]/[`impl_cli_enum!`];
    /// the default interns the tag name.
    fn tag_name_c(self) -> &'static CStr {
        intern_c_str(self.tag_name())
    }
}

/// Returns a `'static` NUL-terminated copy of `s`, allocated once per
/// distinct string (used by the default [`CliEnum::tag_name_c`]).
pub fn intern_c_str(s: &'static str) -> &'static CStr {
    use std::collections::HashMap;
    use std::sync::{Mutex, OnceLock};

    static INTERNED: OnceLock<Mutex<HashMap<&'static str, &'static CStr>>> = OnceLock::new();
    let mut map = INTERNED
        .get_or_init(|| Mutex::new(HashMap::new()))
        .lock()
        .unwrap_or_else(|e| e.into_inner());
    map.entry(s).or_insert_with(|| {
        let owned = std::ffi::CString::new(s).unwrap_or_default();
        Box::leak(owned.into_boxed_c_str())
    })
}

/// A Zig `union(enum)` that can be parsed with the built-in `tag:value`
/// rule. Generated by [`cli_union!`].
pub trait TaggedUnion: Sized {
    /// The Zig tag names in declaration order.
    const TAG_NAMES: &'static [&'static str];

    /// Zig `@tagName(std.meta.activeTag(self))`.
    fn tag_name(&self) -> &'static str;

    /// Parse the value for the variant named `tag`. Returns `None` if no
    /// variant is named `tag`.
    fn parse_tag(tag: &str, value: &str) -> Option<Result<Self, Error>>;
}

/// A Zig `packed struct` of bools. Generated by [`cli_flags!`].
pub trait PackedStruct: Sized + Default {
    /// The Zig field names in declaration order.
    const FIELD_NAMES: &'static [&'static str];

    fn get_field(&self, index: usize) -> bool;
    fn set_field(&mut self, index: usize, value: bool);
}

/// Static information about a parseable field.
#[derive(Debug, Clone, Copy)]
pub struct FieldInfo {
    /// The Zig field name, i.e. the CLI flag / config key.
    pub name: &'static str,

    /// The field's attributes in order; `Some(line)` for each doc comment
    /// line (as written, after `///`), `None` for other attributes. Use
    /// [`FieldInfo::doc_lines`] or [`FieldInfo::help`].
    pub docs: &'static [Option<&'static str>],

    /// The valid enum values (see [`ParseCli::ENUM_VALUES`]).
    pub enum_values: Option<&'static [&'static str]>,
}

impl FieldInfo {
    /// The raw doc comment lines (text after `///`).
    pub fn doc_lines(&self) -> impl Iterator<Item = &'static str> + '_ {
        self.docs.iter().filter_map(|d| *d)
    }

    /// Whether the field has doc comments (Zig
    /// `@hasDecl(help_strings.Config, field)`).
    pub fn has_help(&self) -> bool {
        self.doc_lines().next().is_some()
    }

    /// The help string for this field, built like Zig's `helpgen`: the doc
    /// comment lines with their common leading-space prefix removed, joined
    /// with newlines.
    pub fn help(&self) -> String {
        let prefix = self
            .doc_lines()
            .filter_map(|line| line.bytes().position(|c| c != b' '))
            .min()
            .unwrap_or(0);
        let mut result = String::new();
        for (i, line) in self.doc_lines().enumerate() {
            if i > 0 {
                result.push('\n');
            }
            result.push_str(&line[prefix.min(line.len())..]);
        }
        result
    }
}

/// The comptime field reflection of a struct, generated by [`cli_struct!`].
pub trait Fields: Sized {
    /// All parseable (non-`_`) fields in declaration order.
    const FIELDS: &'static [FieldInfo];

    /// Zig `parseIntoField(T, alloc, dst, key, value)`.
    fn parse_into_field(&mut self, key: &str, value: Option<&str>) -> Result<(), Error>;

    /// Zig `parseAutoStruct(T, alloc, v, default_)`.
    fn parse_auto_struct(v: &str, default_: Option<&Self>) -> Result<Self, Error>;

    /// The index of the field named `name` in [`Fields::FIELDS`].
    fn field_index(name: &str) -> Option<usize> {
        Self::FIELDS.iter().position(|f| f.name == name)
    }
}

/// Per-field formatting, generated by `cli_struct!` with `with { format }`.
pub trait FormatFields: Fields {
    /// Format field `index` of [`Fields::FIELDS`] with
    /// [`config::formatter::format_entry`](crate::config::formatter::format_entry).
    fn format_field(
        &self,
        index: usize,
        writer: &mut dyn fmt::Write,
    ) -> Result<(), crate::config::formatter::Error>;
}

/// Per-field comparison, generated by `cli_struct!` with `with { changed }`.
pub trait ChangedFields: Fields {
    /// Returns true if field `index` of [`Fields::FIELDS`] differs between
    /// `self` and `other` (Zig `!deepEqual(...)`).
    fn field_changed(&self, other: &Self, index: usize) -> bool;
}

/// The function type for a compatibility handler. The compatibility
/// handler is documented in the [`parse`] function documentation.
///
/// The function type should return bool if the compatibility was
/// handled, and false otherwise. If false is returned then the
/// naturally occurring error will continue to be processed as if
/// this compatibility handler was not present.
///
/// Compatibility handlers aren't allowed to return errors because
/// they're generally only called in error cases, so we already have
/// an error message to show users. If there is an error in handling
/// the compatibility, then the handler should return false.
pub type CompatibilityHandler<T> = fn(dst: &mut T, key: &str, value: Option<&str>) -> bool;

/// The optional decls/fields that [`parse`] looks for on the destination
/// type. All methods have defaults matching a Zig struct without them.
pub trait ParseHooks: Fields {
    /// Zig: the `_diagnostics: DiagnosticList` field. When this returns
    /// `Some`, diagnostics are tracked and only allocation errors are
    /// returned from [`parse`].
    fn diagnostics_mut(&mut self) -> Option<&mut DiagnosticList> {
        None
    }

    /// Zig: the `compatibility` decl
    /// (`std.StaticStringMap(CompatibilityHandler(T))`).
    fn compatibility(key: &str) -> Option<CompatibilityHandler<Self>> {
        let _ = key;
        None
    }

    /// Zig: `parseManuallyHook(self, alloc, arg, iter) !bool`. Returns
    /// false if parsing should halt.
    fn parse_manually_hook<I: ArgIterator + ?Sized>(
        &mut self,
        arg: &str,
        iter: &mut I,
    ) -> Result<bool, Error> {
        let _ = (arg, iter);
        Ok(true)
    }

    /// Zig: the `help` decl, called for `--help`/`-h`. `None` means the type
    /// has no `help` decl (the argument is then parsed normally).
    fn help(&mut self) -> Option<Result<(), Error>> {
        None
    }
}

/// An iterator of arguments (Zig: any type with `next() ?[]const u8` and
/// optionally `location(alloc) !?diags.Location`).
pub trait ArgIterator {
    fn next(&mut self) -> Option<String>;

    /// Returns a location for a diagnostic message.
    fn location(&self) -> Option<Location> {
        None
    }
}

impl<T: ArgIterator + ?Sized> ArgIterator for &mut T {
    fn next(&mut self) -> Option<String> {
        (**self).next()
    }

    fn location(&self) -> Option<Location> {
        (**self).location()
    }
}

