    // The worked example from the module documentation.
    mod worked_example {
        use crate::cli::args::{
            self, cli_enum, cli_flags, cli_struct, compatibility_renamed, ArgIterator,
            ChangedFields, CompatibilityHandler, Error, Fields, FormatFields, ParseCli,
            ParseHooks, StringZ,
        };
        use crate::cli::diagnostics::DiagnosticList;
        use crate::config::formatter::{self, EntryFormatter, FormatEntry};

        cli_enum! {
            /// Valid values for confirm-close-surface
            /// c_int because it needs to be extern compatible
            #[repr(C)]
            pub enum ConfirmCloseSurface {
                False => "false",
                True => "true",
                Always => "always",
            }
        }

        cli_flags! {
            /// Shell integration features
            pub struct ShellIntegrationFeatures {
                pub cursor: bool = true,
                pub sudo: bool = false,
                pub ssh_env as "ssh-env": bool = false,
            }
        }

        /// Zig: `pub fn parseCLI(input: ?[]const u8) !Color` (1 arg).
        #[derive(Debug, Clone, Copy, PartialEq, Eq)]
        pub struct Color {
            pub r: u8,
            pub g: u8,
            pub b: u8,
        }

        impl ParseCli for Color {
            fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
                let input = input.ok_or(Error::ValueRequired)?;
                let hex = input.strip_prefix('#').unwrap_or(input);
                if hex.len() != 6 {
                    return Err(Error::Other("InvalidFormat"));
                }
                let c = |i: usize| {
                    u8::from_str_radix(&hex[i..i + 2], 16).map_err(|_| Error::InvalidValue)
                };
                Ok(Color {
                    r: c(0)?,
                    g: c(2)?,
                    b: c(4)?,
                })
            }
        }

        impl FormatEntry for Color {
            fn format_entry(&self, f: &mut EntryFormatter<'_>) -> Result<(), formatter::Error> {
                f.format_entry(&format!("#{:02x}{:02x}{:02x}", self.r, self.g, self.b))
            }
        }

        /// Zig: `pub fn parseCLI(self: *Self, alloc: Allocator, input: ?[]const u8) !void`
        /// (mutating) plus `clone`, `equal`, `formatEntry`.
        #[derive(Debug, Clone, Default, PartialEq)]
        pub struct RepeatableString {
            pub list: Vec<StringZ>,
        }

        impl ParseCli for RepeatableString {
            fn parse_cli(&mut self, input: Option<&str>) -> Result<(), Error> {
                let value = input.ok_or(Error::ValueRequired)?;
                // Empty value resets the list
                if value.is_empty() {
                    self.list.clear();
                    return Ok(());
                }
                self.list.push(value.into());
                Ok(())
            }

            fn parse_cli_new(input: Option<&str>) -> Result<Self, Error> {
                args::parse_cli_new_from_default(input)
            }
        }

        impl FormatEntry for RepeatableString {
            fn format_entry(&self, f: &mut EntryFormatter<'_>) -> Result<(), formatter::Error> {
                if self.list.is_empty() {
                    return f.format_entry(&());
                }
                for v in &self.list {
                    f.format_entry(v)?;
                }
                Ok(())
            }
        }

        cli_struct! {
            /// Config is the main config struct.
            #[derive(Debug, Clone)]
            pub struct Config {
                /// The font families to use.
                ///
                /// This configuration can be repeated multiple times.
                pub font_family as "font-family": RepeatableString = RepeatableString::default(),
                /// Font size in points.
                pub font_size as "font-size": f32 = 13.0,
                pub language: Option<StringZ> = None,
                pub background: Color = Color { r: 0x28, g: 0x2c, b: 0x34 },
                pub confirm_close_surface as "confirm-close-surface": ConfirmCloseSurface =
                    ConfirmCloseSurface::True,
                pub shell_integration_features as "shell-integration-features":
                    ShellIntegrationFeatures = ShellIntegrationFeatures::default(),
                pub background_blur as "background-blur": u8 = 0,
                pub bold_is_bright as "bold-is-bright": bool = false,
            }
            // Zig fields starting with `_` (never parsed, formatted or compared).
            private {
                pub _diagnostics: DiagnosticList = DiagnosticList::default(),
                pub _xdg_terminal_exec: bool = false,
            }
            with { format, changed, custom_hooks }
        }

        impl ParseHooks for Config {
            fn diagnostics_mut(&mut self) -> Option<&mut DiagnosticList> {
                Some(&mut self._diagnostics)
            }

            // Zig: `pub const compatibility = std.StaticStringMap(...)`.
            fn compatibility(key: &str) -> Option<CompatibilityHandler<Self>> {
                match key {
                    "background-blur-radius" => {
                        Some(compatibility_renamed!(Config, "background-blur"))
                    }
                    "old-bold" => Some(compat_old_bold),
                    _ => None,
                }
            }

            fn parse_manually_hook<I: ArgIterator + ?Sized>(
                &mut self,
                arg: &str,
                iter: &mut I,
            ) -> Result<bool, Error> {
                if arg == "-e" {
                    while iter.next().is_some() {}
                    return Ok(false);
                }
                Ok(true)
            }
        }

        fn compat_old_bold(cfg: &mut Config, _key: &str, value: Option<&str>) -> bool {
            match args::parse_bool(value.unwrap_or("t")) {
                Ok(b) => {
                    cfg.bold_is_bright = b;
                    true
                }
                Err(_) => false,
            }
        }

        #[test]
        fn worked_example() {
            let mut cfg = Config::default();
            let mut iter = args::LineIterator::init(
                "font-family = A\nfont-family=B\nfont-size = 14\nbackground-blur-radius=20\n\
                 old-bold\nconfirm-close-surface=always\nshell-integration-features=no-cursor,ssh-env\n\
                 background=#ff0000\nlanguage=de\nnope=1\nbackground=#ff\n"
                    .as_bytes(),
            );
            args::parse(&mut cfg, &mut iter).unwrap();
            assert_eq!(14.0, cfg.font_size);
            assert_eq!(20, cfg.background_blur);
            assert!(cfg.bold_is_bright);
            assert_eq!(ConfirmCloseSurface::Always, cfg.confirm_close_surface);
            assert!(!cfg.shell_integration_features.cursor);
            assert!(cfg.shell_integration_features.ssh_env);
            assert_eq!(Color { r: 255, g: 0, b: 0 }, cfg.background);
            assert_eq!(Some(StringZ::from("de")), cfg.language);
            assert_eq!(2, cfg.font_family.list.len());

            let diags = cfg._diagnostics.items();
            assert_eq!(2, diags.len());
            assert_eq!("unknown field", diags[0].message.as_str());
            assert_eq!("unknown error error.InvalidFormat", diags[1].message.as_str());

            // Formatting all fields (Zig `formatter_file.zig`).
            let mut out = String::new();
            for i in 0..Config::FIELDS.len() {
                cfg.format_field(i, &mut out).unwrap();
            }
            assert_eq!(
                "font-family = A\nfont-family = B\nfont-size = 14\nlanguage = de\n\
                 background = #ff0000\nconfirm-close-surface = always\n\
                 shell-integration-features = no-cursor,no-sudo,ssh-env\n\
                 background-blur = 20\nbold-is-bright = true\n",
                out
            );

            // Changed fields (Zig `Config.changed`).
            let default = Config::default();
            let changed: Vec<&str> = (0..Config::FIELDS.len())
                .filter(|&i| default.field_changed(&cfg, i))
                .map(|i| Config::FIELDS[i].name)
                .collect();
            assert_eq!(Config::FIELDS.len(), changed.len());

            // Help strings (Zig `help_strings.Config.@"font-family"`).
            assert_eq!(
                "The font families to use.\n\nThis configuration can be repeated multiple times.",
                Config::FIELDS[0].help()
            );

            // Enum values are listed in diagnostics.
            assert_eq!(
                Some(&["false", "true", "always"][..]),
                Config::FIELDS[Config::field_index("confirm-close-surface").unwrap()].enum_values
            );

            // parseManuallyHook stops parsing.
            let mut iter = args::ArgIteratorGeneral::init("--font-size=10 -e foo --font-size=12");
            args::parse(&mut cfg, &mut iter).unwrap();
            assert_eq!(10.0, cfg.font_size);
        }
    }
