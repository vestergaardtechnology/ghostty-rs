/// Parse the command line arguments from iter into dst.
///
/// dst must be a struct defined with [`cli_struct!`]. The fields and their
/// types will be used to determine the valid CLI flags. See the tests in
/// this file as an example. For field types that are structs, the struct
/// can implement [`ParseCli`] to do custom parsing.
///
/// If the destination type returns a list from
/// [`ParseHooks::diagnostics_mut`] then any diagnostic messages will be
/// added to that list. When diagnostics are present, only allocation
/// errors will be returned.
///
/// If the destination type implements [`ParseHooks::compatibility`], it
/// will be used to handle backwards compatibility for fields with the given
/// name. The field name doesn't need to exist (so you can setup
/// compatibility for removed fields). The value is a function that will be
/// called when all other parsing fails for that field. If a field changes
/// such that the old values would NOT error, then the caller should handle
/// that downstream after parsing is done, not through this method.
pub fn parse<T: ParseHooks, I: ArgIterator + ?Sized>(dst: &mut T, iter: &mut I) -> Result<(), Error> {
    while let Some(arg) = iter.next() {
        // Do manual parsing if we have a hook for it.
        if !dst.parse_manually_hook(&arg, iter)? {
            return Ok(());
        }

        // If the destination supports help then we check for it, call
        // the help function and return.
        if arg == "--help" || arg == "-h" {
            if let Some(result) = dst.help() {
                result?;
                return Ok(());
            }
        }

        // If this doesn't start with "--" then it isn't a config
        // flag. We don't support positional arguments or configuration
        // values set with spaces so this is an error.
        if !arg.starts_with("--") {
            let location = Location::from_iter(&*iter);
            let Some(diags) = dst.diagnostics_mut() else {
                return Err(Error::InvalidField);
            };

            // Add our diagnostic
            diags.append(Diagnostic {
                key: StringZ::from(arg.as_str()),
                message: StringZ::from("invalid field"),
                location,
            });

            continue;
        }

        let mut key: &str = &arg[2..];
        let value: Option<&str> = match key.find('=') {
            // If the arg has "=" then the value is after the "=".
            Some(idx) => {
                let value = &key[idx + 1..];
                key = &key[..idx];
                Some(value)
            }
            None => None,
        };

        if let Err(err) = dst.parse_into_field(key, value) {
            // If we get an error parsing a field, then we try to fall
            // back to compatibility handlers if able.
            if let Some(handler) = T::compatibility(key) {
                if handler(dst, key, value) {
                    log::info!(
                        target: "cli",
                        "compatibility handler for {} handled error, you may be using a deprecated field: {}",
                        key,
                        err,
                    );
                    continue;
                }
            }

            let message: StringZ = match err {
                // OOM is not recoverable since we need to allocate to
                // track more error messages.
                Error::OutOfMemory => return Err(err),
                Error::InvalidField => "unknown field".into(),
                Error::ValueRequired => format_value_required::<T>(key).into(),
                Error::InvalidValue => format_invalid_value::<T>(key, value).into(),
                other => format!("unknown error {}", other).into(),
            };

            let location = Location::from_iter(&*iter);
            let Some(diags) = dst.diagnostics_mut() else {
                return Err(err);
            };

            // Add our diagnostic
            diags.append(Diagnostic {
                key: StringZ::from(key),
                message,
                location,
            });
        }
    }

    Ok(())
}

/// Implementation of a renamed-field compatibility handler: parse `value`
/// into the field `to` instead. See [`compatibility_renamed!`], which
/// builds a [`CompatibilityHandler`] around this (Zig
/// `compatibilityRenamed(T, to)`).
pub fn parse_renamed<T: Fields>(dst: &mut T, to: &str, value: Option<&str>) -> bool {
    debug_assert!(T::field_index(to).is_some(), "renamed field {to} must exist");

    match dst.parse_into_field(to, value) {
        Ok(()) => true,
        Err(err) => {
            log::warn!(target: "cli", "error parsing renamed field {}: {}", to, err);
            false
        }
    }
}

/// Convenience macro to create a compatibility handler that renames a
/// field to `to` (Zig `compatibilityRenamed(T, to)`):
/// `compatibility_renamed!(Config, "background-blur")`.
#[allow(unused_macros)]
macro_rules! compatibility_renamed {
    ($T:ty, $to:literal) => {
        (|dst: &mut $T, _key: &str, value: ::core::option::Option<&str>| -> bool {
            $crate::cli::args::parse_renamed::<$T>(dst, $to, value)
        }) as $crate::cli::args::CompatibilityHandler<$T>
    };
}
pub(crate) use compatibility_renamed;

fn format_value_required<T: Fields>(key: &str) -> String {
    let mut result = String::from("value required");
    format_values::<T>(key, &mut result);
    result
}

fn format_invalid_value<T: Fields>(key: &str, value: Option<&str>) -> String {
    let mut result = format!("invalid value \"{}\"", value.unwrap_or("null"));
    format_values::<T>(key, &mut result);
    result
}

fn format_values<T: Fields>(key: &str, writer: &mut String) {
    for f in T::FIELDS {
        if f.name == key {
            if let Some(values) = f.enum_values {
                writer.push_str(", valid values are: ");
                for (i, field) in values.iter().enumerate() {
                    if i != 0 {
                        writer.push_str(", ");
                    }
                    writer.push_str(field);
                }
            }
            break;
        }
    }
}

/// Parse a single key/value pair into the destination type T.
pub fn parse_into_field<T: Fields>(dst: &mut T, key: &str, value: Option<&str>) -> Result<(), Error> {
    dst.parse_into_field(key, value)
}

/// The per-field part of `parseIntoField` that the generated
/// [`Fields::parse_into_field`] calls for the matching field.
///
/// If the value is empty string (set but empty string), then we reset the
/// value to the default: the type's `init` if it has one, else the field
/// default if the field has one. Otherwise the value is parsed with
/// [`ParseCli`].
pub fn parse_field_value<T: ParseCli>(
    slot: &mut T,
    value: Option<&str>,
    default: Option<fn() -> T>,
) -> Result<(), Error> {
    if value == Some("") {
        // Set default value if possible.
        if let Some(result) = T::init_cli() {
            *slot = result?;
            return Ok(());
        }
        if let Some(default) = default {
            *slot = default();
            return Ok(());
        }
    }

    slot.parse_cli(value)
}

/// Like [`parse_field_value`] but for a field that has no value yet (Zig
/// parses into `undefined` memory in `parseAutoStruct`/`parseTaggedUnion`).
pub fn parse_field_new<T: ParseCli>(value: Option<&str>, default: Option<fn() -> T>) -> Result<T, Error> {
    if value == Some("") {
        if let Some(result) = T::init_cli() {
            return result;
        }
        if let Some(default) = default {
            return Ok(default());
        }
    }

    T::parse_cli_new(value)
}

/// Used by the code generated for [`Fields::parse_auto_struct`].
#[doc(hidden)]
pub fn parse_auto_struct_field<T: ParseCli>(
    slot: &mut Option<T>,
    value: Option<&str>,
    default: Option<fn() -> T>,
) -> Result<(), Error> {
    match slot {
        Some(v) => parse_field_value(v, value, default),
        None => {
            *slot = Some(parse_field_new(value, default)?);
            Ok(())
        }
    }
}

/// Splits one auto-struct entry into its trimmed key and value. The value
/// may be quoted, in which case it is decoded as a Zig string literal.
#[doc(hidden)]
pub fn auto_struct_entry(entry: &str) -> Result<(&str, Cow<'_, str>), Error> {
    // Find the key/value, trimming whitespace. The value may be quoted
    // which we strip the quotes from.
    let idx = entry.find(':').ok_or(Error::InvalidValue)?;
    let key = trim(&entry[..idx], WHITESPACE);
    let value = trim(&entry[idx + 1..], WHITESPACE);

    // Detect a quoted string.
    if value.len() >= 2 && value.starts_with('"') && value.ends_with('"') {
        // Decode a double-quoted string as a Zig string literal.
        let parsed = string::parse_write(value.as_bytes()).map_err(|_| Error::InvalidValue)?;
        return Ok((key, Cow::Owned(String::from_utf8_lossy(&parsed).into_owned())));
    }

    Ok((key, Cow::Borrowed(value)))
}

/// Zig `std.mem.trim(u8, s, chars)`.
pub fn trim<'a>(s: &'a str, chars: &str) -> &'a str {
    s.trim_matches(|c| chars.contains(c))
}

/// Zig `parseTaggedUnion(T, alloc, v)`.
pub fn parse_tagged_union<T: TaggedUnion>(v: &str) -> Result<T, Error> {
    // Get the union tag that is being set. We support values with no colon
    // if the value is void so its not an error to have no colon.
    let colon_idx = v.find(':').unwrap_or(v.len());
    let tag_str = trim(&v[..colon_idx], WHITESPACE);
    let value = if colon_idx < v.len() { &v[colon_idx + 1..] } else { "" };

    // Find the field in the union that matches the tag.
    T::parse_tag(tag_str, value).unwrap_or(Err(Error::InvalidValue))
}

/// The built-in rule for (non-packed) structs without `parseCLI`
/// (Zig `parseStruct` for `.auto` layout). Used by the `parse_cli` extra of
/// [`cli_struct!`].
pub fn parse_struct<T: Fields>(input: Option<&str>) -> Result<T, Error> {
    parse_auto_struct(input.ok_or(Error::ValueRequired)?, None)
}

/// Zig `parseAutoStruct(T, alloc, v, default_)`.
///
/// We split each value by "," allowing for quoting and escaping. Each
/// entry is `key:value`. Fields that aren't set take their value from
/// `default_` if given, else the field default; a required field (no
/// default) that isn't set is an error.
pub fn parse_auto_struct<T: Fields>(v: &str, default_: Option<&T>) -> Result<T, Error> {
    T::parse_auto_struct(v, default_)
}

/// Zig `parsePackedStruct(T, v)`.
pub fn parse_packed_struct<T: PackedStruct>(v: &str) -> Result<T, Error> {
    let mut result = T::default();

    // Allow standalone boolean values like "true" and "false" to
    // turn on or off all of the struct's fields.
    if let Ok(b) = parse_bool(v) {
        for i in 0..T::FIELD_NAMES.len() {
            result.set_field(i, b);
        }
        return Ok(result);
    }

    // We split each value by ","
    'parts: for part_raw in v.split(',') {
        // Determine the field we're looking for and the value. If the
        // field is prefixed with "no-" then we set the value to false.
        const NEGATION_PREFIX: &str = "no-";
        let trimmed = trim(part_raw, WHITESPACE);
        let (part, value) = match trimmed.strip_prefix(NEGATION_PREFIX) {
            Some(rest) => (rest, false),
            None => (trimmed, true),
        };

        for (i, field) in T::FIELD_NAMES.iter().enumerate() {
            if *field == part {
                result.set_field(i, value);
                continue 'parts;
            }
        }

        // No field matched
        return Err(Error::InvalidValue);
    }

    Ok(result)
}

/// Zig `parseBool`.
pub fn parse_bool(v: &str) -> Result<bool, Error> {
    match v {
        "1" | "t" | "T" | "true" => Ok(true),
        "0" | "f" | "F" | "false" => Ok(false),
        _ => Err(Error::InvalidValue),
    }
}

/// Parses an enum value by tag name (the built-in enum rule).
pub fn parse_enum<T: CliEnum>(input: Option<&str>) -> Result<T, Error> {
    T::from_tag(input.ok_or(Error::ValueRequired)?).ok_or(Error::InvalidValue)
}

/// Errors from [`parse_int`]/[`parse_float`] (Zig `std.fmt.ParseIntError`
/// and `ParseFloatError`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParseNumberError {
    InvalidCharacter,
    Overflow,
}

fn char_to_digit(c: u8, base: u32) -> Result<i128, ParseNumberError> {
    let value = match c {
        b'0'..=b'9' => (c - b'0') as u32,
        b'A'..=b'Z' => (c - b'A') as u32 + 10,
        b'a'..=b'z' => (c - b'a') as u32 + 10,
        _ => return Err(ParseNumberError::InvalidCharacter),
    };
    if value >= base {
        return Err(ParseNumberError::InvalidCharacter);
    }
    Ok(value as i128)
}

/// Port of Zig's `std.fmt.parseInt(T, buf, base)`. With `base == 0` the
/// base is detected from a `0x`/`0o`/`0b` prefix. Underscores are allowed
/// between digits.
pub fn parse_int<T: TryFrom<i128>>(buf: &str, base: u8) -> Result<T, ParseNumberError> {
    let bytes = buf.as_bytes();
    if bytes.is_empty() {
        return Err(ParseNumberError::InvalidCharacter);
    }
    let (negative, bytes) = match bytes[0] {
        b'+' => (false, &bytes[1..]),
        b'-' => (true, &bytes[1..]),
        _ => (false, bytes),
    };
    if bytes.is_empty() {
        return Err(ParseNumberError::InvalidCharacter);
    }

    let mut base = base as u32;
    let mut digits = bytes;
    if base == 0 {
        // Treat is as a decimal number by default.
        base = 10;
        // Detect the base by looking at buf prefix.
        if bytes.len() > 2 && bytes[0] == b'0' {
            match bytes[1].to_ascii_lowercase() {
                b'b' => {
                    base = 2;
                    digits = &bytes[2..];
                }
                b'o' => {
                    base = 8;
                    digits = &bytes[2..];
                }
                b'x' => {
                    base = 16;
                    digits = &bytes[2..];
                }
                _ => {}
            }
        }
    }

    if digits[0] == b'_' || digits[digits.len() - 1] == b'_' {
        return Err(ParseNumberError::InvalidCharacter);
    }

    let mut accumulate: i128 = 0;
    for &c in digits {
        if c == b'_' {
            continue;
        }
        let digit = char_to_digit(c, base)?;
        accumulate = accumulate
            .checked_mul(base as i128)
            .ok_or(ParseNumberError::Overflow)?;
        accumulate = if negative {
            accumulate.checked_sub(digit)
        } else {
            accumulate.checked_add(digit)
        }
        .ok_or(ParseNumberError::Overflow)?;
    }

    T::try_from(accumulate).map_err(|_| ParseNumberError::Overflow)
}

/// Removes underscores that sit between two digits (Zig number literal
/// syntax). Returns `None` if an underscore is misplaced.
fn strip_digit_underscores(s: &str, hex: bool) -> Option<Cow<'_, str>> {
    if !s.contains('_') {
        return Some(Cow::Borrowed(s));
    }
    let bytes = s.as_bytes();
    let is_digit = |c: u8| if hex { c.is_ascii_hexdigit() } else { c.is_ascii_digit() };
    let mut out = String::with_capacity(s.len());
    for (i, &c) in bytes.iter().enumerate() {
        if c == b'_' {
            let prev_ok = i > 0 && is_digit(bytes[i - 1]);
            let next_ok = i + 1 < bytes.len() && is_digit(bytes[i + 1]);
            if !prev_ok || !next_ok {
                return None;
            }
            continue;
        }
        out.push(c as char);
    }
    Some(Cow::Owned(out))
}

/// Port of Zig's `std.fmt.parseFloat(f64, buf)`: decimal or hexadecimal
/// (`0x1.8p3`) floats, `inf`/`infinity`/`nan`, optional sign, underscores
/// between digits.
pub fn parse_float(buf: &str) -> Result<f64, ParseNumberError> {
    if buf.is_empty() {
        return Err(ParseNumberError::InvalidCharacter);
    }
    let (negative, rest) = match buf.as_bytes()[0] {
        b'+' => (false, &buf[1..]),
        b'-' => (true, &buf[1..]),
        _ => (false, buf),
    };
    let sign = if negative { -1.0 } else { 1.0 };

    let lower = rest.to_ascii_lowercase();
    if lower == "inf" || lower == "infinity" {
        return Ok(sign * f64::INFINITY);
    }
    if lower == "nan" {
        return Ok(f64::NAN);
    }

    if lower.starts_with("0x") {
        let hex = strip_digit_underscores(&rest[2..], true).ok_or(ParseNumberError::InvalidCharacter)?;
        return parse_hex_float(&hex).map(|v| sign * v);
    }

    let dec = strip_digit_underscores(rest, false).ok_or(ParseNumberError::InvalidCharacter)?;
    // Rust's grammar would accept a nested sign here; Zig doesn't.
    if dec.starts_with(['+', '-']) || dec.is_empty() {
        return Err(ParseNumberError::InvalidCharacter);
    }
    if !dec
        .bytes()
        .all(|c| c.is_ascii_digit() || matches!(c, b'.' | b'e' | b'E' | b'+' | b'-'))
    {
        return Err(ParseNumberError::InvalidCharacter);
    }
    dec.parse::<f64>()
        .map(|v| sign * v)
        .map_err(|_| ParseNumberError::InvalidCharacter)
}

fn parse_hex_float(s: &str) -> Result<f64, ParseNumberError> {
    let (mantissa_str, exp_str) = match s.find(['p', 'P']) {
        Some(idx) => (&s[..idx], Some(&s[idx + 1..])),
        None => (s, None),
    };

    let mut mantissa: f64 = 0.0;
    let mut frac_digits: i32 = 0;
    let mut seen_dot = false;
    let mut any_digit = false;
    for c in mantissa_str.bytes() {
        if c == b'.' {
            if seen_dot {
                return Err(ParseNumberError::InvalidCharacter);
            }
            seen_dot = true;
            continue;
        }
        let d = (c as char).to_digit(16).ok_or(ParseNumberError::InvalidCharacter)?;
        any_digit = true;
        mantissa = mantissa * 16.0 + d as f64;
        if seen_dot {
            frac_digits += 1;
        }
    }
    if !any_digit {
        return Err(ParseNumberError::InvalidCharacter);
    }

    let exp: i32 = match exp_str {
        Some(e) => parse_int::<i32>(e, 10)?,
        None => 0,
    };

    Ok(mantissa * 2f64.powi(exp - 4 * frac_digits))
}

