/// Defines a struct whose fields can be parsed from `--key=value`
/// arguments and implements [`Fields`] for it. See the module docs for a
/// full example.
///
/// ```ignore
/// cli_struct! {
///     /// struct docs
///     #[derive(Debug, Clone)]
///     pub struct Options {
///         /// field docs (become FieldInfo::docs)
///         pub a: String = String::new(),
///         pub b_f as "b-f": bool = true,   // Zig name differs from the Rust name
///         pub c: Option<u8>,               // no default
///     }
///     private { pub _diagnostics: DiagnosticList = DiagnosticList::default() }
///     with { parse_cli, format, changed, custom_hooks }
/// }
/// ```
///
/// Extras:
/// * `parse_cli`: `impl ParseCli` using the auto-struct rule
///   (`a:hello,b:42`), like a Zig struct field type without `parseCLI`.
/// * `format`: `impl FormatFields` (requires `FormatEntry` on all fields).
/// * `changed`: `impl ChangedFields` (requires `PartialEq` on all fields).
/// * `custom_hooks`: don't generate the empty `impl ParseHooks`.
#[allow(unused_macros)]
macro_rules! cli_struct {
    // Internal: normalized definition.
    (@define
        attrs [$($sattr:tt)*]
        vis [$svis:vis]
        name $Name:ident
        fields [$( { [$([$($fattr:tt)*])*] [$fvis:vis] $field:ident [$($fname:literal)?] ($fty:ty) [$($fdefault:expr)?] } )*]
        private [$( { [$($pattr:tt)*] [$pvis:vis] $pfield:ident ($pty:ty) ($pdefault:expr) } )*]
        extras [$($extra:ident)*]
    ) => {
        $($sattr)*
        $svis struct $Name {
            // Field attributes (mostly doc comments) are dropped while rustdoc
            // collects doctests: config docs use indented (Markdown) code
            // blocks for config examples, which are not Rust.
            $( $(#[cfg_attr(not(doctest), $($fattr)*)])* $fvis $field: $fty, )*
            $( $($pattr)* $pvis $pfield: $pty, )*
        }

        impl $crate::cli::args::Fields for $Name {
            const FIELDS: &'static [$crate::cli::args::FieldInfo] = &[
                $(
                    $crate::cli::args::FieldInfo {
                        name: $crate::cli::args::__cli_name!($field; $($fname)?),
                        docs: &[ $( $crate::cli::args::__cli_doc_line!($($fattr)*), )* ],
                        enum_values: <$fty as $crate::cli::args::ParseCli>::ENUM_VALUES,
                    },
                )*
            ];

            #[allow(unused_variables)]
            fn parse_into_field(
                &mut self,
                key: &str,
                value: ::core::option::Option<&str>,
            ) -> ::core::result::Result<(), $crate::cli::args::Error> {
                // Fields starting with "_" are never parsed.
                if key.starts_with('_') {
                    return ::core::result::Result::Err($crate::cli::args::Error::InvalidField);
                }

                $(
                    if key == $crate::cli::args::__cli_name!($field; $($fname)?) {
                        return $crate::cli::args::parse_field_value::<$fty>(
                            &mut self.$field,
                            value,
                            $crate::cli::args::__cli_default_fn!($fty; $($fdefault)?),
                        );
                    }
                )*

                ::core::result::Result::Err($crate::cli::args::Error::InvalidField)
            }

            #[allow(unused_variables, unused_mut, unreachable_code, unused_labels)]
            fn parse_auto_struct(
                v: &str,
                default_: ::core::option::Option<&Self>,
            ) -> ::core::result::Result<Self, $crate::cli::args::Error> {
                // Keep track of which fields were set so we can error if a
                // required field was not set.
                $( let mut $field: ::core::option::Option<$fty> = ::core::option::Option::None; )*

                // We split each value by "," allowing for quoting and escaping.
                let mut iter = $crate::cli::comma_splitter::CommaSplitter::init(v);
                'entries: while let ::core::option::Option::Some(entry) = iter.next()? {
                    let (key, value) = $crate::cli::args::auto_struct_entry(entry)?;
                    let value: &str = &value;

                    $(
                        if key == $crate::cli::args::__cli_name!($field; $($fname)?) {
                            $crate::cli::args::parse_auto_struct_field::<$fty>(
                                &mut $field,
                                ::core::option::Option::Some(value),
                                $crate::cli::args::__cli_default_fn!($fty; $($fdefault)?),
                            )?;
                            continue 'entries;
                        }
                    )*

                    // Fields starting with "_" can't be set.
                    $(
                        if key == ::core::stringify!($pfield) {
                            return ::core::result::Result::Err($crate::cli::args::Error::InvalidField);
                        }
                    )*

                    // No field matched
                    return ::core::result::Result::Err($crate::cli::args::Error::InvalidValue);
                }

                // Ensure all required fields are set. If we're given a
                // default value then we inherit those. Otherwise we use the
                // default values as specified by the struct.
                ::core::result::Result::Ok(Self {
                    $(
                        $field: match $field {
                            ::core::option::Option::Some(x) => x,
                            ::core::option::Option::None => match default_ {
                                ::core::option::Option::Some(d) => ::core::clone::Clone::clone(&d.$field),
                                ::core::option::Option::None => {
                                    $crate::cli::args::__cli_default_or_invalid!($($fdefault)?)
                                }
                            },
                        },
                    )*
                    $(
                        $pfield: match default_ {
                            ::core::option::Option::Some(d) => ::core::clone::Clone::clone(&d.$pfield),
                            ::core::option::Option::None => $pdefault,
                        },
                    )*
                })
            }
        }

        $crate::cli::args::cli_struct!(@extras $Name
            [$( { [$([$($fattr)*])*] [$fvis] $field [$($fname)?] ($fty) [$($fdefault)?] } )*]
            [default_hooks]
            [$($extra)*]);
    };

    // Internal: extras muncher.
    (@extras $Name:ident $fields:tt [$hooks:ident] []) => {
        $crate::cli::args::cli_struct!(@hooks $hooks $Name);
    };
    (@extras $Name:ident $fields:tt [$hooks:ident] [custom_hooks $($rest:ident)*]) => {
        $crate::cli::args::cli_struct!(@extras $Name $fields [custom_hooks] [$($rest)*]);
    };
    (@extras $Name:ident $fields:tt [$hooks:ident] [parse_cli $($rest:ident)*]) => {
        impl $crate::cli::args::ParseCli for $Name {
            fn parse_cli_new(
                input: ::core::option::Option<&str>,
            ) -> ::core::result::Result<Self, $crate::cli::args::Error> {
                $crate::cli::args::parse_struct::<Self>(input)
            }
        }
        $crate::cli::args::cli_struct!(@extras $Name $fields [$hooks] [$($rest)*]);
    };
    (@extras $Name:ident $fields:tt [$hooks:ident] [format $($rest:ident)*]) => {
        $crate::cli::args::cli_struct!(@format $Name $fields);
        $crate::cli::args::cli_struct!(@extras $Name $fields [$hooks] [$($rest)*]);
    };
    (@extras $Name:ident $fields:tt [$hooks:ident] [changed $($rest:ident)*]) => {
        $crate::cli::args::cli_struct!(@changed $Name $fields);
        $crate::cli::args::cli_struct!(@extras $Name $fields [$hooks] [$($rest)*]);
    };
    (@hooks default_hooks $Name:ident) => {
        impl $crate::cli::args::ParseHooks for $Name {}
    };
    (@hooks custom_hooks $Name:ident) => {};

    (@format $Name:ident [$( { [$($fattr:tt)*] [$fvis:vis] $field:ident [$($fname:literal)?] ($fty:ty) [$($fdefault:tt)*] } )*]) => {
        impl $crate::cli::args::FormatFields for $Name {
            #[allow(unused_assignments, unused_mut, unused_variables)]
            fn format_field(
                &self,
                index: usize,
                writer: &mut dyn ::core::fmt::Write,
            ) -> ::core::result::Result<(), $crate::config::formatter::Error> {
                let mut i: usize = 0;
                $(
                    if index == i {
                        return $crate::config::formatter::format_entry(
                            $crate::cli::args::__cli_name!($field; $($fname)?),
                            &self.$field,
                            writer,
                        );
                    }
                    i += 1;
                )*
                ::core::debug_assert!(false, "field index out of range");
                ::core::result::Result::Ok(())
            }
        }
    };

    (@changed $Name:ident [$( { [$($fattr:tt)*] [$fvis:vis] $field:ident [$($fname:literal)?] ($fty:ty) [$($fdefault:tt)*] } )*]) => {
        impl $crate::cli::args::ChangedFields for $Name {
            #[allow(unused_assignments, unused_mut, unused_variables)]
            fn field_changed(&self, other: &Self, index: usize) -> bool {
                let mut i: usize = 0;
                $(
                    if index == i {
                        return self.$field != other.$field;
                    }
                    i += 1;
                )*
                ::core::debug_assert!(false, "field index out of range");
                false
            }
        }
    };

    // Every field has a default: also implement `Default`.
    (
        $(#[$smeta:meta])*
        $svis:vis struct $Name:ident {
            $(
                $(#[$($fattr:tt)*])*
                $fvis:vis $field:ident $(as $fname:literal)? : $fty:ty = $fdefault:expr
            ),* $(,)?
        }
        $(private {
            $( $(#[$pmeta:meta])* $pvis:vis $pfield:ident : $pty:ty = $pdefault:expr ),* $(,)?
        })?
        $(with { $($extra:ident),* $(,)? })?
    ) => {
        $crate::cli::args::cli_struct!(@define
            attrs [$(#[$smeta])*]
            vis [$svis]
            name $Name
            fields [$( { [$([$($fattr)*])*] [$fvis] $field [$($fname)?] ($fty) [$fdefault] } )*]
            private [$($( { [$(#[$pmeta])*] [$pvis] $pfield ($pty) ($pdefault) } )*)?]
            extras [$($($extra)*)?]
        );

        impl ::core::default::Default for $Name {
            fn default() -> Self {
                Self {
                    $( $field: $fdefault, )*
                    $($( $pfield: $pdefault, )*)?
                }
            }
        }
    };

    // Some fields have no default.
    (
        $(#[$smeta:meta])*
        $svis:vis struct $Name:ident {
            $(
                $(#[$($fattr:tt)*])*
                $fvis:vis $field:ident $(as $fname:literal)? : $fty:ty $(= $fdefault:expr)?
            ),* $(,)?
        }
        $(private {
            $( $(#[$pmeta:meta])* $pvis:vis $pfield:ident : $pty:ty = $pdefault:expr ),* $(,)?
        })?
        $(with { $($extra:ident),* $(,)? })?
    ) => {
        $crate::cli::args::cli_struct!(@define
            attrs [$(#[$smeta])*]
            vis [$svis]
            name $Name
            fields [$( { [$([$($fattr)*])*] [$fvis] $field [$($fname)?] ($fty) [$($fdefault)?] } )*]
            private [$($( { [$(#[$pmeta])*] [$pvis] $pfield ($pty) ($pdefault) } )*)?]
            extras [$($($extra)*)?]
        );
    };
}
pub(crate) use cli_struct;

/// Defines an enum whose Zig tag names are user-visible and implements
/// [`CliEnum`], [`FormatEntry`](crate::config::formatter::FormatEntry) and
/// (unless `@custom_parse` is given first) [`ParseCli`] for it. Adds
/// `#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]`.
///
/// ```ignore
/// cli_enum! {
///     /// docs
///     #[repr(C)]
///     pub enum NonNativeFullscreen {
///         False => "false",
///         True => "true",
///         VisibleMenu => "visible-menu",
///         PaddedNotch = 3 => "padded-notch",   // explicit discriminant
///     }
/// }
/// ```
#[allow(unused_macros)]
macro_rules! cli_enum {
    (@define [$mode:ident]
        $(#[$meta:meta])*
        $vis:vis enum $Name:ident {
            $( $(#[$vmeta:meta])* $variant:ident $(= $disc:expr)? => $tag:literal ),* $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        $vis enum $Name {
            $( $(#[$vmeta])* $variant $(= $disc)?, )*
        }

        $crate::cli::args::impl_cli_enum!(@impls [$mode] $Name { $( $variant => $tag ),* });
    };
    (@custom_parse $($rest:tt)*) => {
        $crate::cli::args::cli_enum!(@define [custom] $($rest)*);
    };
    ($($rest:tt)*) => {
        $crate::cli::args::cli_enum!(@define [parse] $($rest)*);
    };
}
pub(crate) use cli_enum;

/// Implements [`CliEnum`], `FormatEntry` and (unless `@custom_parse`)
/// [`ParseCli`] for an enum defined elsewhere:
/// `impl_cli_enum!(crate::terminal::cursor::Style { Bar => "bar", Block => "block" });`
#[allow(unused_macros)]
macro_rules! impl_cli_enum {
    (@impls [$mode:ident] $T:ty { $( $variant:ident => $tag:literal ),* $(,)? }) => {
        impl $crate::cli::args::CliEnum for $T {
            const FIELD_NAMES: &'static [&'static str] = &[$($tag),*];

            fn tag_name(self) -> &'static str {
                match self {
                    $( Self::$variant => $tag, )*
                }
            }

            fn from_tag(tag: &str) -> ::core::option::Option<Self> {
                match tag {
                    $( $tag => ::core::option::Option::Some(Self::$variant), )*
                    _ => ::core::option::Option::None,
                }
            }

            fn tag_name_c(self) -> &'static ::core::ffi::CStr {
                match self {
                    $( Self::$variant => match ::core::ffi::CStr::from_bytes_with_nul(
                        ::core::concat!($tag, "\0").as_bytes(),
                    ) {
                        ::core::result::Result::Ok(s) => s,
                        ::core::result::Result::Err(_) => ::core::unreachable!(),
                    }, )*
                }
            }
        }

        impl $crate::config::formatter::FormatEntry for $T {
            fn format_entry(
                &self,
                formatter: &mut $crate::config::formatter::EntryFormatter<'_>,
            ) -> ::core::result::Result<(), $crate::config::formatter::Error> {
                $crate::config::formatter::format_enum(
                    formatter,
                    $crate::cli::args::CliEnum::tag_name(*self),
                )
            }
        }

        $crate::cli::args::impl_cli_enum!(@parse [$mode] $T);
    };
    (@parse [parse] $T:ty) => {
        impl $crate::cli::args::ParseCli for $T {
            const ENUM_VALUES: ::core::option::Option<&'static [&'static str]> =
                ::core::option::Option::Some(<Self as $crate::cli::args::CliEnum>::FIELD_NAMES);

            fn parse_cli_new(
                input: ::core::option::Option<&str>,
            ) -> ::core::result::Result<Self, $crate::cli::args::Error> {
                $crate::cli::args::parse_enum::<Self>(input)
            }
        }
    };
    (@parse [custom] $T:ty) => {};
    (@custom_parse $T:ty { $($body:tt)* }) => {
        $crate::cli::args::impl_cli_enum!(@impls [custom] $T { $($body)* });
    };
    ($T:ty { $($body:tt)* }) => {
        $crate::cli::args::impl_cli_enum!(@impls [parse] $T { $($body)* });
    };
}
pub(crate) use impl_cli_enum;

/// Defines a Zig-style `packed struct` of bools and implements
/// [`PackedStruct`], `Default`, `FormatEntry` (`a,no-b`) and (unless
/// `@custom_parse` is given first) [`ParseCli`] ([`parse_packed_struct`]).
/// Adds `#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]` and
/// `to_bits`/`from_bits` (first field is the least significant bit, as in
/// Zig).
///
/// ```ignore
/// cli_flags! {
///     pub struct FontSyntheticStyle {
///         pub bold: bool = true,
///         pub italic: bool = true,
///         pub bold_italic as "bold-italic": bool = true,
///     }
/// }
/// ```
#[allow(unused_macros)]
macro_rules! cli_flags {
    (@define [$mode:ident]
        $(#[$meta:meta])*
        $vis:vis struct $Name:ident {
            $( $(#[$fmeta:meta])* $fvis:vis $field:ident $(as $fname:literal)? : bool = $default:expr ),* $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        $vis struct $Name {
            $( $(#[$fmeta])* $fvis $field: bool, )*
        }

        impl ::core::default::Default for $Name {
            fn default() -> Self {
                Self { $( $field: $default, )* }
            }
        }

        #[allow(dead_code)]
        impl $Name {
            /// The number of bits in the packed representation.
            pub const BITS: u32 =
                <Self as $crate::cli::args::PackedStruct>::FIELD_NAMES.len() as u32;

            /// The packed integer representation (Zig `@bitCast`).
            #[allow(unused_assignments, unused_mut)]
            pub fn to_bits(self) -> u64 {
                let mut bits: u64 = 0;
                let mut i: u32 = 0;
                $(
                    if self.$field {
                        bits |= 1u64 << i;
                    }
                    i += 1;
                )*
                bits
            }

            /// Inverse of [`Self::to_bits`].
            #[allow(unused_assignments, unused_mut, unused_variables)]
            pub fn from_bits(bits: u64) -> Self {
                let mut i: u32 = 0;
                $(
                    let $field = bits & (1u64 << i) != 0;
                    i += 1;
                )*
                Self { $( $field, )* }
            }
        }

        impl $crate::cli::args::PackedStruct for $Name {
            const FIELD_NAMES: &'static [&'static str] =
                &[$( $crate::cli::args::__cli_name!($field; $($fname)?) ),*];

            #[allow(unused_assignments, unused_mut)]
            fn get_field(&self, index: usize) -> bool {
                let mut i: usize = 0;
                $(
                    if index == i {
                        return self.$field;
                    }
                    i += 1;
                )*
                false
            }

            #[allow(unused_assignments, unused_mut)]
            fn set_field(&mut self, index: usize, value: bool) {
                let mut i: usize = 0;
                $(
                    if index == i {
                        self.$field = value;
                        return;
                    }
                    i += 1;
                )*
            }
        }

        impl $crate::config::formatter::FormatEntry for $Name {
            fn format_entry(
                &self,
                formatter: &mut $crate::config::formatter::EntryFormatter<'_>,
            ) -> ::core::result::Result<(), $crate::config::formatter::Error> {
                $crate::config::formatter::format_packed_struct(self, formatter)
            }
        }

        $crate::cli::args::cli_flags!(@parse [$mode] $Name);
    };
    (@parse [parse] $Name:ident) => {
        impl $crate::cli::args::ParseCli for $Name {
            fn parse_cli_new(
                input: ::core::option::Option<&str>,
            ) -> ::core::result::Result<Self, $crate::cli::args::Error> {
                $crate::cli::args::parse_packed_struct::<Self>(
                    input.ok_or($crate::cli::args::Error::ValueRequired)?,
                )
            }
        }
    };
    (@parse [custom] $Name:ident) => {};
    (@custom_parse $($rest:tt)*) => {
        $crate::cli::args::cli_flags!(@define [custom] $($rest)*);
    };
    ($($rest:tt)*) => {
        $crate::cli::args::cli_flags!(@define [parse] $($rest)*);
    };
}
pub(crate) use cli_flags;

#[doc(hidden)]
#[allow(unused_macros)]
macro_rules! __cli_union_pat {
    ($Name:ident, $variant:ident;) => {
        $Name::$variant
    };
    ($Name:ident, $variant:ident; $payload:ty) => {
        $Name::$variant(..)
    };
}
pub(crate) use __cli_union_pat;

#[doc(hidden)]
#[allow(unused_macros)]
macro_rules! __cli_union_parse {
    // Special case void types where we don't need a value.
    ($Name:ident, $variant:ident, $value:ident;) => {
        if !$value.is_empty() {
            ::core::result::Result::Err($crate::cli::args::Error::InvalidValue)
        } else {
            ::core::result::Result::Ok($Name::$variant)
        }
    };
    // Parse the value as if it were a field of this type (Zig builds a
    // one-field struct and uses parseIntoField).
    ($Name:ident, $variant:ident, $value:ident; $payload:ty) => {
        $crate::cli::args::parse_field_new::<$payload>(
            ::core::option::Option::Some($value),
            ::core::option::Option::None,
        )
        .map($Name::$variant)
    };
}
pub(crate) use __cli_union_parse;

/// Defines a Zig-style `union(enum)` and implements [`TaggedUnion`] and
/// (unless `@custom_parse` is given first) [`ParseCli`] with the built-in
/// `tag:value` rule ([`parse_tagged_union`]). Derives nothing.
///
/// ```ignore
/// cli_union! {
///     #[derive(Debug, Clone, PartialEq)]
///     pub enum Value {
///         A(u8) => "a",
///         C => "c",          // void payload
///         D(String) => "d",
///     }
/// }
/// ```
#[allow(unused_macros)]
macro_rules! cli_union {
    (@define [$mode:ident]
        $(#[$meta:meta])*
        $vis:vis enum $Name:ident {
            $( $(#[$vmeta:meta])* $variant:ident $(($payload:ty))? => $tag:literal ),* $(,)?
        }
    ) => {
        $(#[$meta])*
        $vis enum $Name {
            $( $(#[$vmeta])* $variant $(($payload))?, )*
        }

        impl $crate::cli::args::TaggedUnion for $Name {
            const TAG_NAMES: &'static [&'static str] = &[$($tag),*];

            fn tag_name(&self) -> &'static str {
                match self {
                    $( $crate::cli::args::__cli_union_pat!($Name, $variant; $($payload)?) => $tag, )*
                }
            }

            fn parse_tag(
                tag: &str,
                value: &str,
            ) -> ::core::option::Option<::core::result::Result<Self, $crate::cli::args::Error>> {
                $(
                    if tag == $tag {
                        return ::core::option::Option::Some(
                            $crate::cli::args::__cli_union_parse!($Name, $variant, value; $($payload)?),
                        );
                    }
                )*
                ::core::option::Option::None
            }
        }

        $crate::cli::args::cli_union!(@parse [$mode] $Name);
    };
    (@parse [parse] $Name:ident) => {
        impl $crate::cli::args::ParseCli for $Name {
            fn parse_cli_new(
                input: ::core::option::Option<&str>,
            ) -> ::core::result::Result<Self, $crate::cli::args::Error> {
                $crate::cli::args::parse_tagged_union::<Self>(
                    input.ok_or($crate::cli::args::Error::ValueRequired)?,
                )
            }
        }
    };
    (@parse [custom] $Name:ident) => {};
    (@custom_parse $($rest:tt)*) => {
        $crate::cli::args::cli_union!(@define [custom] $($rest)*);
    };
    ($($rest:tt)*) => {
        $crate::cli::args::cli_union!(@define [parse] $($rest)*);
    };
}
pub(crate) use cli_union;

