/// This sets either "ctrl" or "super" to true (but not both)
/// on mods depending on if the build target is Mac or not. On
/// Mac, we default to super (i.e. super+c for copy) and on
/// non-Mac we default to ctrl (i.e. ctrl+c for copy).
pub const fn ctrl_or_super(mods: Mods) -> Mods {
    let mut copy = mods;
    if cfg!(any(target_os = "macos", target_os = "ios")) {
        copy.super_ = true;
    } else {
        copy.ctrl = true;
    }

    copy
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn from_ascii_should_not_return_keypad_keys() {
        assert!(Key::from_ascii(b'0').unwrap() == Key::Digit0);
        assert!(Key::from_ascii(b'*').is_none());
    }

    #[test]
    fn keypad_keys() {
        assert!(Key::Numpad0.keypad());
        assert!(!Key::Digit1.keypad());
    }

    #[test]
    fn w3c() {
        // All our keys should convert to and from the W3C format.
        // We don't support every key in the W3C spec, so we only
        // check the enum fields.
        for key in Key::ALL {
            let w3c_name = key.w3c();
            assert_eq!(key, Key::from_w3c(w3c_name.as_bytes()).unwrap());
        }
    }

    #[test]
    fn ctrl_or_super_test() {
        let m: Mods = super::ctrl_or_super(Mods::EMPTY);

        assert!(m.ctrl_or_super());
    }

    // Port-specific sanity checks of the Rust enum layout against the Zig
    // tag order (the C enum values are the declaration indices).
    #[test]
    fn all_matches_discriminants() {
        for (i, key) in Key::ALL.iter().enumerate() {
            assert_eq!(*key as usize, i);
            assert_eq!(Key::parse(key.as_str().as_bytes()), Some(*key));
        }
    }
}
