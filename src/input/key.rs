    /// or ctrl.
    pub const fn ctrl_or_super(self) -> bool {
        if cfg!(any(target_os = "macos", target_os = "ios")) {
            return matches!(self, Key::MetaLeft | Key::MetaRight);
        }
        matches!(self, Key::ControlLeft | Key::ControlRight)
    }

