    /// Returns true if this is a keypad key.
    pub const fn keypad(self) -> bool {
        // Zig: comptime `std.mem.startsWith(u8, @tagName(tag), "numpad_")`.
        let name = self.as_str().as_bytes();
        let prefix = b"numpad_";
        if name.len() < prefix.len() {
            return false;
        }
        let mut i = 0;
        while i < prefix.len() {
            if name[i] != prefix[i] {
                return false;
            }
            i += 1;
        }
        true
    }

    // Returns the codepoint representing this key, or null if the key is not
    // printable
    pub const fn codepoint(self) -> Option<u32> {
        let mut i = 0;
        while i < CODEPOINT_MAP.len() {
            if CODEPOINT_MAP[i].1 as c_int == self as c_int {
                return Some(CODEPOINT_MAP[i].0);
            }
            i += 1;
        }

        None
    }

