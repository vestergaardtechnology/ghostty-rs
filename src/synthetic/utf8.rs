//! Port of `src/synthetic/Utf8.zig`.
//!
//! STATUS: ported
//!
//! Generates UTF-8.
//!
//! This doesn't yet generate multi-codepoint graphemes, but it
//! has the ability to generate a custom distribution of UTF-8
//! encoding lengths (1, 2, 3, or 4 bytes).

use super::generator::{Error, Generator, Writer};
use super::Random;

/// Possible UTF-8 encoding lengths.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum Utf8Len {
    One = 1,
    Two = 2,
    Three = 3,
    Four = 4,
}

impl Utf8Len {
    /// The index into an `EnumArray(Utf8Len, _)` (declaration order).
    pub const fn index(self) -> usize {
        self as usize - 1
    }

    /// Zig `Indexer.keyForIndex`.
    pub const fn key_for_index(idx: usize) -> Utf8Len {
        match idx {
            0 => Utf8Len::One,
            1 => Utf8Len::Two,
            2 => Utf8Len::Three,
            3 => Utf8Len::Four,
            _ => panic!("invalid Utf8Len index"),
        }
    }

    fn from_backing_int(v: u8) -> Utf8Len {
        Utf8Len::key_for_index(v as usize - 1)
    }
}

#[derive(Debug, Clone, Copy)]
struct InvalidSequence {
    len: u8,
    bytes: [u8; 4],
}

impl InvalidSequence {
    fn slice(&self) -> &[u8] {
        &self.bytes[..self.len as usize]
    }
}

const INVALID_SEQUENCES: [InvalidSequence; 9] = [
    InvalidSequence { len: 1, bytes: [0x80, 0x00, 0x00, 0x00] },
    InvalidSequence { len: 1, bytes: [0xC0, 0x00, 0x00, 0x00] },
    InvalidSequence { len: 1, bytes: [0xFF, 0x00, 0x00, 0x00] },
    InvalidSequence { len: 2, bytes: [0xC2, 0x20, 0x00, 0x00] },
    InvalidSequence { len: 2, bytes: [0xC0, 0xAF, 0x00, 0x00] },
    InvalidSequence { len: 2, bytes: [0x80, 0x80, 0x00, 0x00] },
    InvalidSequence { len: 3, bytes: [0xED, 0xA0, 0x80, 0x00] },
    InvalidSequence { len: 3, bytes: [0xE2, 0x28, 0x7A, 0x00] },
    InvalidSequence { len: 4, bytes: [0xF0, 0x90, 0x28, 0x7A] },
];

/// Generates UTF-8.
#[derive(Debug, Clone)]
pub struct Utf8 {
    /// Random number generator.
    pub rand: Random,

    /// The minimum and maximum length of the generated bytes. The maximum
    /// length will be capped to the length of the buffer passed in if the
    /// buffer length is smaller.
    pub min_len: usize,
    pub max_len: usize,

    /// Probability of a specific UTF-8 encoding length being generated.
    /// The probabilities are weighted relative to each other, so they
    /// can sum greater than 1.0. A length of weight 1.0 and a length
    /// of weight 2.0 will have a 2:1 chance of the latter being
    /// selected.
    ///
    /// If a UTF-8 encoding of a chosen length can't fit into the remaining
    /// buffer, a smaller length will be chosen. For small buffers this may
    /// skew the distribution of lengths.
    ///
    /// Indexed by [`Utf8Len::index`] (Zig `std.enums.EnumArray`).
    pub p_length: [f64; 4],

    /// If true, ASCII codepoints are limited to printable ASCII.
    pub ascii_printable_only: bool,

    /// Probability that the next generated sequence is malformed UTF-8.
    /// This is checked for each emitted sequence while filling a buffer.
    pub invalid_rate: f64,
}

impl Utf8 {
    /// A new generator with the Zig default field values.
    pub fn init(rand: Random) -> Utf8 {
        Utf8 {
            rand,
            min_len: 1,
            max_len: usize::MAX,
            p_length: [1.0; 4],
            ascii_printable_only: false,
            invalid_rate: 0.0,
        }
    }

    /// Zig `p_length.set(k, v)`.
    pub fn set_p_length(&mut self, k: Utf8Len, v: f64) {
        self.p_length[k.index()] = v;
    }

    pub fn generator(&mut self) -> &mut dyn Generator {
        self
    }

    pub fn next(&mut self, writer: &mut Writer<'_>, max_len: usize) -> Result<(), Error> {
        let len = (self
            .rand
            .int_range_at_most_biased::<64>(self.min_len as u64, self.max_len as u64)
            as usize)
            .min(max_len);

        let mut rem: usize = len;
        while rem > 0 {
            if let Some(written) = self.write_invalid(writer, rem)? {
                rem -= written;
                continue;
            }

            let written = self.write_valid(writer, rem)?;
            rem -= written;
        }
        Ok(())
    }

    fn write_invalid(&mut self, writer: &mut Writer<'_>, rem: usize) -> Result<Option<usize>, Error> {
        if self.invalid_rate <= 0.0 || self.rand.float() >= self.invalid_rate {
            return Ok(None);
        }

        let Some(seq) = self.invalid_sequence(rem) else {
            return Ok(None);
        };
        writer.write_all(seq.slice())?;
        Ok(Some(seq.len as usize))
    }

    fn write_valid(&mut self, writer: &mut Writer<'_>, rem: usize) -> Result<usize, Error> {
        loop {
            let utf8_len = self.utf8_len(rem);

            // Generate a UTF-8 sequence that encodes to this length.
            let cp: u32 = match utf8_len {
                Utf8Len::One => {
                    if self.ascii_printable_only {
                        self.rand.int_range_at_most_biased::<21>(0x20, 0x7E) as u32
                    } else {
                        self.rand.int_range_at_most_biased::<21>(0x00, 0x7F) as u32
                    }
                }
                Utf8Len::Two => self.rand.int_range_at_most_biased::<21>(0x80, 0x7FF) as u32,
                Utf8Len::Three => self.rand.int_range_at_most_biased::<21>(0x800, 0xFFFF) as u32,
                Utf8Len::Four => {
                    self.rand.int_range_at_most_biased::<21>(0x10000, 0x10FFFF) as u32
                }
            };

            // Possible (surrogate half), in which case we redo the loop
            // and encode nothing.
            let Some(c) = char::from_u32(cp) else {
                continue;
            };
            debug_assert_eq!(c.len_utf8(), utf8_len as usize);

            let mut buf = [0u8; 4];
            let encoded = c.encode_utf8(&mut buf);
            writer.write_all(encoded.as_bytes())?;
            return Ok(encoded.len());
        }
    }

    fn utf8_len(&mut self, rem: usize) -> Utf8Len {
        let idx = self.rand.weighted_index(&self.p_length);
        let mut utf8_len = Utf8Len::key_for_index(idx);
        debug_assert!(rem > 0);
        while utf8_len as usize > rem {
            // If the chosen length can't fit into the remaining buffer,
            // choose a smaller length.
            utf8_len = Utf8Len::from_backing_int(utf8_len as u8 - 1);
        }
        utf8_len
    }

    fn invalid_sequence(&mut self, rem: usize) -> Option<InvalidSequence> {
        let candidates = &INVALID_SEQUENCES;

        let mut valid_idx = [0usize; INVALID_SEQUENCES.len()];
        let mut valid_len: usize = 0;
        for (i, candidate) in candidates.iter().enumerate() {
            if candidate.len as usize > rem {
                continue;
            }
            valid_idx[valid_len] = i;
            valid_len += 1;
        }

        if valid_len == 0 {
            return None;
        }
        Some(candidates[valid_idx[self.rand.uint_less_than::<64>(valid_len as u64) as usize]])
    }
}

impl Generator for Utf8 {
    fn next(&mut self, writer: &mut Writer<'_>, max_len: usize) -> Result<(), Error> {
        Utf8::next(self, writer, max_len)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::synthetic::{DefaultPrng, FixedWriter};

    #[test]
    fn utf8() {
        let prng = DefaultPrng::init(0);
        let mut buf = [0u8; 256];
        let len = buf.len();
        let mut writer = FixedWriter::fixed(&mut buf);
        let mut v = Utf8::init(prng.random());
        v.min_len = len;
        v.max_len = len;
        let gen = v.generator();
        gen.next(&mut writer, len).unwrap();
        let result = writer.buffered();
        assert_eq!(256, result.len());
        assert!(std::str::from_utf8(result).is_ok());
    }

    #[test]
    fn utf8_printable_ascii_only() {
        let prng = DefaultPrng::init(0);
        let mut buf = [0u8; 256];
        let len = buf.len();
        let mut writer = FixedWriter::fixed(&mut buf);
        let mut v = Utf8 {
            ascii_printable_only: true,
            ..Utf8::init(prng.random())
        };
        v.min_len = len;
        v.max_len = len;
        v.set_p_length(Utf8Len::One, 1.0);
        v.set_p_length(Utf8Len::Two, 0.0);
        v.set_p_length(Utf8Len::Three, 0.0);
        v.set_p_length(Utf8Len::Four, 0.0);

        let gen = v.generator();
        gen.next(&mut writer, len).unwrap();
        let result = writer.buffered();
        assert_eq!(256, result.len());
        assert!(std::str::from_utf8(result).is_ok());
        for &c in result {
            assert!(c.is_ascii_graphic() || c == b' ');
        }
    }

    #[test]
    fn utf8_malformed_output() {
        let prng = DefaultPrng::init(0);
        let mut buf = [0u8; 256];
        let len = buf.len();
        let mut writer = FixedWriter::fixed(&mut buf);
        let mut v = Utf8 {
            invalid_rate: 1.0,
            ..Utf8::init(prng.random())
        };
        v.min_len = len;
        v.max_len = len;

        let gen = v.generator();
        gen.next(&mut writer, len).unwrap();
        let result = writer.buffered();
        assert_eq!(256, result.len());
        assert!(std::str::from_utf8(result).is_err());
    }
}
