//! Port of `src/terminal/snapshot/fixture.zig`.
//!
//! STATUS: ported
//!
//! Test-only support for reviewable snapshot golden fixtures.
//!
//! Snapshot compatibility references are stored as annotated hexadecimal text
//! under `testdata/`. Each byte is written as exactly two hexadecimal digits.
//! Whitespace is insignificant, and `#` begins a comment through the end of the
//! line. This permits field, record, and absolute-offset annotations without
//! changing the bytes embedded by a test.
//!
//! `parse` validates and decodes an `include_str!` (Zig: `@embedFile`).
//! Tests should encode their native value, compare the generated bytes with
//! that embedded reference using `expect_equal`, and then decode the
//! reference itself. This keeps encoding regression coverage separate from
//! backwards-decoding coverage.
//!
//! `expect_equal` formats a fresh candidate on every run. Matching candidates
//! remain in the test's temporary directory. A mismatch copies the candidate
//! to the repository root, reports its path and first differing byte, and
//! fails without modifying the checked-in reference. After reviewing an
//! intentional wire change, a maintainer manually replaces the reference.
//! Fixture filenames include the snapshot version so a future format adds new
//! references instead of overwriting compatibility data for an older version.
//!
//! ## Kaitai
//!
//! Every fixture has three machine-readable comment fields:
//!
//! ```text
//! # Kaitai type: page_payload
//! # Kaitai params:
//! # Kaitai offset: 0
//! ```
//!
//! These select a type from `snapshot.ksy`, its whitespace-separated
//! parameters, and the byte offset where parsing begins. The Kaitai verifier
//! discovers fixtures from the filesystem and uses this metadata instead of
//! maintaining a parallel filename table. Generated candidates copy the
//! metadata from their checked-in reference.
//!
//! Notes on the port:
//! - Zig parses fixtures at comptime and reports syntax errors with
//!   `@compileError`. The port parses at run time and panics instead.
//! - `expect_equal` panics (fails the test) on a mismatch instead of
//!   returning `error.TestExpectedEqual`. Reference paths are resolved
//!   relative to the crate root (`CARGO_MANIFEST_DIR`).

use std::fmt::Write as _;
use std::path::PathBuf;

use super::envelope;
use super::record;

const LOG_TARGET: &str = "snapshot_fixture";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Bytes,
    Page,
    Snapshot,
}

/// Decode an annotated hexadecimal fixture.
///
/// Whitespace is ignored. `#` begins a comment that continues through the end
/// of the line. Every other token must be exactly two hexadecimal digits.
pub fn parse(source: &str) -> Vec<u8> {
    let source = source.as_bytes();
    let mut result = Vec::with_capacity(decoded_len(source));
    let mut source_index = 0;

    while source_index < source.len() {
        // Comments and layout are purely for reviewers and contribute no
        // bytes to the embedded reference.
        skip_ignored(source, &mut source_index);
        if source_index == source.len() {
            break;
        }

        // Every data token is one complete byte. Parse it directly rather
        // than accepting variable-width integers or other hex syntax.
        if source_index + 1 >= source.len() {
            panic!("snapshot fixture ends with one hex digit");
        }
        result.push(hex_nibble(source[source_index]) << 4 | hex_nibble(source[source_index + 1]));
        source_index += 2;

        // Requiring a separator catches accidental third digits and makes
        // the accepted grammar match the formatter below.
        if source_index < source.len() && !source[source_index].is_ascii_whitespace() && source[source_index] != b'#' {
            panic!("snapshot fixture hex bytes must be separated by whitespace");
        }
    }

    result
}

/// Compare generated bytes with a checked-in reference.
///
/// A formatted candidate is always created in a temporary directory. On a
/// mismatch it is copied into the repository root before the test fails.
pub fn expect_equal(kind: Kind, reference_path: &str, candidate_name: &str, expected: &[u8], actual: &[u8]) {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));

    // A unique temporary directory for this candidate.
    let tmp = std::env::temp_dir().join(format!(
        "ghostty-snapshot-fixture-{}-{}",
        std::process::id(),
        TMP_COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    std::fs::create_dir_all(&tmp).expect("create fixture temp dir");
    struct Cleanup(PathBuf);
    impl Drop for Cleanup {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }
    let _cleanup = Cleanup(tmp.clone());

    // Kaitai parser selection lives in the reference itself. Read the textual
    // source so generated candidates preserve that metadata even though the
    // byte comparison below uses the decoded reference.
    let reference_source =
        std::fs::read_to_string(root.join(reference_path)).expect("read snapshot fixture reference");

    // Always materialize a candidate, even when it will match. This keeps the
    // generation path exercised on every test run while avoiding repository
    // artifacts for the normal successful case.
    let tmp_path = tmp.join(candidate_name);
    {
        let mut candidate = String::new();
        format(kind, &reference_source, actual, &mut candidate).expect("format snapshot fixture candidate");
        std::fs::write(&tmp_path, candidate).expect("write snapshot fixture candidate");
    }

    // Matching candidates remain in the temporary directory and disappear
    // with its cleanup.
    if expected == actual {
        return;
    }

    // Copy the candidate to the stable, user-visible repository-root name.
    let candidate_path = root.join(candidate_name);
    std::fs::copy(&tmp_path, &candidate_path).expect("copy snapshot fixture candidate");

    // Report the first useful comparison point. When one byte sequence is a
    // prefix of the other, this is the shared length where they diverge.
    let shared_len = expected.len().min(actual.len());
    let difference = expected[..shared_len]
        .iter()
        .zip(&actual[..shared_len])
        .position(|(e, a)| e != a)
        .unwrap_or(shared_len);
    log::error!(
        target: LOG_TARGET,
        "snapshot fixture differs reference={} candidate={} offset=0x{:x} expected_len={} actual_len={}",
        reference_path,
        candidate_path.display(),
        difference,
        expected.len(),
        actual.len(),
    );
    panic!(
        "snapshot fixture differs reference={} candidate={} offset=0x{:x} expected_len={} actual_len={}",
        reference_path,
        candidate_path.display(),
        difference,
        expected.len(),
        actual.len(),
    );
}

static TMP_COUNTER: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

fn decoded_len(source: &[u8]) -> usize {
    // This is a complete validation pass, not just a count. Invalid syntax
    // therefore fails before parse fills its result.
    let mut index = 0;
    let mut result = 0;
    while index < source.len() {
        skip_ignored(source, &mut index);
        if index == source.len() {
            break;
        }

        if index + 1 >= source.len() {
            panic!("snapshot fixture ends with one hex digit");
        }
        let _ = hex_nibble(source[index]);
        let _ = hex_nibble(source[index + 1]);
        result += 1;
        index += 2;

        if index < source.len() && !source[index].is_ascii_whitespace() && source[index] != b'#' {
            panic!("snapshot fixture hex bytes must be separated by whitespace");
        }
    }
    result
}

fn skip_ignored(source: &[u8], index: &mut usize) {
    while *index < source.len() {
        // Layout whitespace is unrestricted so fixtures can group fields and
        // keep deterministic sixteen-byte output lines.
        if source[*index].is_ascii_whitespace() {
            *index += 1;
            continue;
        }

        // A comment consumes the rest of its line. The newline itself is
        // consumed by the whitespace case on the next iteration.
        if source[*index] != b'#' {
            return;
        }
        while *index < source.len() && source[*index] != b'\n' {
            *index += 1;
        }
    }
}

fn hex_nibble(value: u8) -> u8 {
    match value {
        b'0'..=b'9' => value - b'0',
        b'a'..=b'f' => value - b'a' + 10,
        b'A'..=b'F' => value - b'A' + 10,
        _ => panic!("snapshot fixture contains a non-hex digit"),
    }
}

/// Errors from `format` (Zig: `std.Io.Writer.Error || error{InvalidKaitaiMetadata}`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FormatError {
    WriteFailed,
    InvalidKaitaiMetadata,
}

impl From<std::fmt::Error> for FormatError {
    fn from(_: std::fmt::Error) -> Self {
        FormatError::WriteFailed
    }
}

fn format(kind: Kind, reference_source: &str, bytes: &[u8], writer: &mut String) -> Result<(), FormatError> {
    // Every generated candidate starts with enough maintenance context to be
    // understandable when copied out of a failing test's temp directory.
    writer.push_str("# Ghostty snapshot fixture\n");
    write_kaitai_metadata(reference_source, writer)?;
    write!(
        writer,
        "# Wire version: {}\n\
         # Generated by its snapshot test; review before replacing.\n\
         # On mismatch, the candidate is copied to the repository root.\n",
        envelope::VERSION
    )?;

    // Small values only need a hex dump. Larger compound formats get
    // structure-aware section labels without changing their decoded bytes.
    match kind {
        Kind::Bytes => write_section("encoded bytes", bytes, 0, bytes.len(), writer)?,
        Kind::Page => format_page(bytes, writer)?,
        Kind::Snapshot => format_snapshot(bytes, writer)?,
    }
    Ok(())
}

fn write_kaitai_metadata(reference_source: &str, writer: &mut String) -> Result<(), FormatError> {
    const PREFIXES: [&str; 3] = ["# Kaitai type:", "# Kaitai params:", "# Kaitai offset:"];
    let mut found = [false; PREFIXES.len()];

    for untrimmed in reference_source.split('\n') {
        let line = untrimmed.trim_matches(|c| c == ' ' || c == '\r');
        for (prefix, seen) in PREFIXES.iter().zip(found.iter_mut()) {
            if !line.starts_with(prefix) {
                continue;
            }
            if *seen {
                return Err(FormatError::InvalidKaitaiMetadata);
            }
            *seen = true;
            writeln!(writer, "{line}")?;
            break;
        }
    }

    if found.iter().any(|seen| !seen) {
        return Err(FormatError::InvalidKaitaiMetadata);
    }
    Ok(())
}

fn format_page(bytes: &[u8], writer: &mut String) -> Result<(), std::fmt::Error> {
    // PAGE version 1 has a twenty-byte fixed header. The remainder is
    // self-describing through the counts and dimensions in that header.
    let header_end = bytes.len().min(20);
    write_section("PAGE header", bytes, 0, header_end, writer)?;
    if header_end < bytes.len() {
        write_section(
            "style and hyperlink tables, rows, and cells",
            bytes,
            header_end,
            bytes.len(),
            writer,
        )?;
    }
    Ok(())
}

fn format_snapshot(bytes: &[u8], writer: &mut String) -> Result<(), std::fmt::Error> {
    // A complete snapshot begins with its unframed envelope. Clamp this first
    // section so a partially generated candidate can still be inspected.
    let envelope_end = bytes.len().min(envelope::ENCODED_LEN);
    write_section("snapshot envelope", bytes, 0, envelope_end, writer)?;

    // Walk record framing only far enough to annotate boundaries. The emitted
    // hex remains authoritative; this formatter never repairs candidate data.
    let mut offset = envelope_end;
    while offset < bytes.len() {
        // A partial header cannot provide a safe payload boundary, so preserve
        // the remaining bytes as one explicitly incomplete section.
        if bytes.len() - offset < record::Header::LEN {
            write_section("trailing partial record", bytes, offset, bytes.len(), writer)?;
            return Ok(());
        }

        // Tag and payload length are the first six bytes of every record
        // header. CRC validation belongs to the codec test, not this formatter.
        let tag_raw = u16::from_le_bytes([bytes[offset], bytes[offset + 1]]);
        let payload_len = u32::from_le_bytes(bytes[offset + 2..offset + 6].try_into().unwrap());

        // Clamp the section to the available candidate bytes. This makes a
        // truncated payload reviewable instead of indexing beyond the slice.
        let record_end = bytes.len().min(offset + record::Header::LEN + payload_len as usize);

        // Known tags make the annotated diff readable. Preserve unknown tags
        // numerically so formatter output is still useful for encoder bugs.
        match record::Tag(tag_raw).name() {
            Some(name) => write!(
                writer,
                "\n# offset 0x{offset:0>8x}: {name} record, payload {payload_len} bytes\n"
            )?,
            None => write!(
                writer,
                "\n# offset 0x{offset:0>8x}: unknown record {tag_raw}, payload {payload_len} bytes\n"
            )?,
        }
        write_hex(bytes, offset, record_end, writer)?;
        offset = record_end;
    }
    Ok(())
}

fn write_section(name: &str, bytes: &[u8], start: usize, end: usize, writer: &mut String) -> Result<(), std::fmt::Error> {
    // Sections begin on a fresh line and carry their absolute wire offset.
    write!(writer, "\n# offset 0x{start:0>8x}: {name}\n")?;
    write_hex(bytes, start, end, writer)
}

fn write_hex(bytes: &[u8], start: usize, end: usize, writer: &mut String) -> Result<(), std::fmt::Error> {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut offset = start;
    while offset < end {
        // Lowercase, sixteen-byte lines provide stable textual diffs. The
        // trailing offset is a comment and is ignored by parse.
        let line_end = end.min(offset + 16);
        for (index, &byte) in bytes[offset..line_end].iter().enumerate() {
            if index != 0 {
                writer.push(' ');
            }
            writer.push(DIGITS[(byte >> 4) as usize] as char);
            writer.push(DIGITS[(byte & 0x0f) as usize] as char);
        }
        writeln!(writer, " # 0x{offset:0>8x}")?;
        offset = line_end;
    }
    Ok(())
}
